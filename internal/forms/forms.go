// ErrUserAborted is returned by Run when the user cancels with ctrl+c.
var ErrUserAborted = errors.New("user aborted")

var (
	accent   = lipgloss.Color("#38BDF8")
	dimmed   = lipgloss.Color("#64748B")
	subtle   = lipgloss.Color("#475569")
	errColor = lipgloss.Color("#F87171")
)

type fieldKind int

const (
	kindInput fieldKind = iota
	kindText
	kindSelect
	kindConfirm
)

// Option is a choice in a select field: Label is shown, Value is stored.
type Option struct {
	Label string
	Value string
}

// NewOption returns a select option.
func NewOption(label, value string) Option {
	return Option{Label: label, Value: value}
}

// Field is one question. Its answer is written to the variable passed to the
// constructor as the user edits it.
type Field struct {
	kind        fieldKind
	title       string
	description string
	validate    func(string) error
	err         error

	text   *string // input, text and select answers
	yes    *bool   // confirm answer
	secret bool

	options  []Option
	cursor   int
	halfPage int // rows moved by ctrl+d and ctrl+u, set from the visible window

	input textinput.Model
	area  textarea.Model
}

// NewInput asks for a single line of text, starting from *value.
func NewInput(value *string) *Field {
	in := textinput.New()
	in.SetValue(*value)
	return &Field{kind: kindInput, text: value, input: in}
}

// textRows is the editor height when the terminal has room for it.
const textRows = 6

// NewText asks for multi-line text such as JSON, starting from *value.
// alt+enter or ctrl+j inserts a newline; enter moves on.
func NewText(value *string) *Field {
	area := textarea.New()
	area.ShowLineNumbers = false
	area.Prompt = ""
	area.KeyMap.InsertNewline.SetKeys("alt+enter", "ctrl+j")
	area.SetHeight(textRows)
	area.SetValue(*value)
	return &Field{kind: kindText, text: value, area: area}
}

// NewSelect asks for one of options, starting at the option matching *value.
func NewSelect(value *string, options ...Option) *Field {
	f := &Field{kind: kindSelect, text: value, options: options}
	for i, o := range options {
		if o.Value == *value {
			f.cursor = i
			break
		}
	}
	if len(options) > 0 {
		*value = options[f.cursor].Value
	}
	return f
}

// NewConfirm asks a yes/no question, starting from *value.
func NewConfirm(value *bool) *Field {
	return &Field{kind: kindConfirm, yes: value}
}

