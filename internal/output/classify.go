// Must match the generated SDK's wrapper around http.Client.Do failures.
const sdkSendErrorMarker = "error sending request:"

func isConnectionError(err error) bool {
	if err == nil {
		return false
	}
	var urlErr *url.Error
	if errors.As(err, &urlErr) {
		return urlErr.Op != "parse"
	}
	var opErr *net.OpError
	if errors.As(err, &opErr) {
		return true
	}
	var dnsErr *net.DNSError
	if errors.As(err, &dnsErr) {
		return true
	}
	if errors.Is(err, context.DeadlineExceeded) {
		return true
	}
	return strings.HasPrefix(err.Error(), sdkSendErrorMarker)
}

const sdkDecodeErrorMarker = "error unmarshaling json response body:"

func isProtocolError(err error) bool {
	if err == nil {
		return false
	}
	var syntaxErr *json.SyntaxError
	var typeErr *json.UnmarshalTypeError
	if errors.As(err, &syntaxErr) || errors.As(err, &typeErr) {
		return true
	}
	return strings.Contains(err.Error(), sdkDecodeErrorMarker)
}

