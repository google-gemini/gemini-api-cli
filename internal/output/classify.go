func classificationMessage(bodyMap, errorObject map[string]any, err error, rawBody string) string {
	if message, _ := errorObject["message"].(string); message != "" {
		return message
	}
	if message, _ := bodyMap["message"].(string); message != "" {
		return message
	}
	if message, _ := bodyMap["error"].(string); message != "" {
		return message
	}
	message := err.Error()
	if rawBody == "" {
		return message
	}
	if strings.HasSuffix(message, "\n"+rawBody) {
		if trimmed := strings.TrimSuffix(message, "\n"+rawBody); trimmed != "" {
			return trimmed
		}
	}
	if strings.HasSuffix(message, rawBody) {
		if trimmed := strings.TrimSuffix(message, rawBody); trimmed != "" {
			return trimmed
		}
	}
	return message
}

func assembleHints(cmd *cobra.Command, err error, c Classification, bodyMap, errorObject map[string]any, ruleHints []string, useReasonRule bool) []string {
	hints := append(leadingHints(cmd, err, c.Reason), serverHints(bodyMap, errorObject)...)
	if useReasonRule && ruleHints != nil {
		hints = append(hints, ruleHints...)
	} else if declared, ok := declaredTypeHints[c.Type]; ok {
		hints = append(hints, declared...)
	} else {
		hints = append(hints, builtinTypeHints[c.Type]...)
	}
	hints = append(hints, errorCLIHints(err)...)
	if declared := declaredCommandHints(cmd); declared != nil && c.Reason != "" {
		hints = append(hints, declared[c.Reason]...)
	}
	seen := make(map[string]bool, len(hints))
	deduped := make([]string, 0, len(hints))
	for _, hint := range hints {
		if hint == "" || seen[hint] {
			continue
		}
		seen[hint] = true
		deduped = append(deduped, hint)
	}
	return deduped
}

func serverHints(bodyMap, errorObject map[string]any) []string {
	for _, source := range []map[string]any{errorObject, bodyMap} {
		raw, exists := source["hints"]
		if !exists {
			continue
		}
		items, ok := raw.([]any)
		if !ok {
			continue
		}
		var hints []string
		for _, item := range items {
			if hint, ok := item.(string); ok && hint != "" {
				hints = append(hints, hint)
			}
		}
		if len(hints) > 0 {
			return hints
		}
	}
	return nil
}

