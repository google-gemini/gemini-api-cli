// sameWriter reports whether two writers are known to be the same value.
// Interface equality panics when both operands hold the same non-comparable
// dynamic type (e.g. a func adapter or a struct value with slice fields), and
// a child command inheriting the root's writer puts the identical value on
// both sides, so == only runs for comparable types. A non-comparable writer
// is conservatively reported as distinct; the caller then pins the resolved
// writer instead of restoring inheritance, which keeps output correct.
func sameWriter(a, b io.Writer) bool {
	ta := reflect.TypeOf(a)
	if ta != reflect.TypeOf(b) {
		return false
	}
	if ta != nil && !ta.Comparable() {
		return false
	}
	return a == b
}

// localOutWriter returns the command's own output writer; nil means the
// command resolves its writer through the parent chain, so a later
// SetOut(nil) keeps that inheritance intact.
func localOutWriter(cmd *cobra.Command) io.Writer {
	resolved := cmd.OutOrStdout()
	if parent := cmd.Parent(); parent != nil {
		if sameWriter(resolved, parent.OutOrStdout()) {
			return nil
		}
	} else if resolved == os.Stdout {
		return nil
	}
	return resolved
}

