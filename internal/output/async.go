func snapshotAsyncResponse(response interface{}) (asyncSnapshot, error) {
	if httpResponse := extractHTTPResponse(response); httpResponse != nil {
		contentType := strings.ToLower(httpResponse.Header.Get("Content-Type"))
		if strings.Contains(contentType, "text/event-stream") || strings.Contains(contentType, "application/jsonl") || strings.Contains(contentType, "application/json-seq") {
			return asyncSnapshot{}, fmt.Errorf("server returned a stream (%s) where a discrete JSON response was required", contentType)
		}
	}
	headers := extractResponseHeaders(response).Clone()
	raw, rawErr := tryReadRawBody(response)
	if rawErr != nil {
		return asyncSnapshot{}, rawErr
	}
	if len(raw) == 0 {
		content := extractResultContent(response)
		if content == nil {
			return asyncSnapshot{}, errors.New("response body is empty")
		}
		var err error
		raw, err = marshalJSON(content)
		if err != nil {
			return asyncSnapshot{}, err
		}
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.UseNumber()
	var parsed interface{}
	if err := decoder.Decode(&parsed); err != nil {
		return asyncSnapshot{}, fmt.Errorf("response body is not valid JSON: %w", err)
	}
	return asyncSnapshot{raw: raw, parsed: parsed, headers: headers}, nil
}

