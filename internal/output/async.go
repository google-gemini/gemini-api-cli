func asyncResume(prefix, id string) string {
	if id == "" {
		return prefix
	}
	safe := true
	for _, char := range id {
		if !strings.ContainsRune("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-._~:/", char) {
			safe = false
			break
		}
	}
	if safe {
		return prefix + " " + id
	}
	return prefix + " '" + strings.ReplaceAll(id, "'", "'\"'\"'") + "'"
}

func asyncElapsed(elapsed time.Duration) string {
	if elapsed < time.Second {
		return "0s"
	}
	return elapsed.Round(time.Second).String()
}

// asyncFailureDetail extracts the human failure message through the
// declared bindings (default "error"/"message").
func asyncFailureDetail(cfg *asyncConfig, payload interface{}) string {
	object, ok := payload.(map[string]interface{})
	if !ok {
		return ""
	}
	errorMember, ok := object[cfg.ErrorField].(map[string]interface{})
	if !ok {
		return ""
	}
	message, _ := errorMember[cfg.ErrorMessageField].(string)
	return message
}
