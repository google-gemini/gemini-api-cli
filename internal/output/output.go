func wantsHeaders(cmd *cobra.Command) bool {
	includeHeaders, _ := flagutil.GetBoolFlag(cmd, "include-headers")
	return includeHeaders
}

// extractResponseHeaders extracts HTTP response headers from a response envelope.
// Uses extractHTTPResponse to get all HTTP headers (not just spec-defined ones).
func extractResponseHeaders(res interface{}) http.Header {
	httpRes := extractHTTPResponse(res)
	if httpRes == nil {
		return nil
	}
	return httpRes.Header
}

// extractErrorResponseHeaders extracts HTTP response headers from an SDK error.
// Error types store *http.Response in a RawResponse field.
func extractErrorResponseHeaders(err error) http.Header {
	for current := err; current != nil; current = errors.Unwrap(current) {
		v, ok := derefToStruct(reflect.ValueOf(current))
		if !ok {
			continue
		}
		rawResp := v.FieldByName("RawResponse")
		if rawResp.IsValid() && rawResp.CanInterface() {
			if r, ok := rawResp.Interface().(*http.Response); ok && r != nil {
				return r.Header
			}
		}
	}
	return nil
}

// flattenHeaders converts http.Header (map[string][]string) to map[string]interface{}
// for JSON output. Single-value headers are flattened to strings; multi-value headers
// remain as arrays. Key order is not guaranteed; callers relying on deterministic output
// should sort separately (json.Marshal sorts map keys; printResponseHeadersPretty sorts explicitly).
func flattenHeaders(headers http.Header) map[string]interface{} {
	if len(headers) == 0 {
		return nil
	}
	result := make(map[string]interface{}, len(headers))
	for k, v := range headers {
		if len(v) == 1 {
			result[k] = v[0]
		} else {
			result[k] = v
		}
	}
	return result
}

// injectHeaders merges flattened response headers into a parsed JSON data structure.
// If data is a map, adds _response_headers as a sibling key.
// If data is nil, returns just the headers.
// Otherwise wraps as {"_result": data, "_response_headers": headers}.
func injectHeaders(data interface{}, headers http.Header) interface{} {
	flat := flattenHeaders(headers)
	if flat == nil {
		return data
	}
	if data == nil {
		return map[string]interface{}{
			"_response_headers": flat,
		}
	}
	if m, ok := data.(map[string]interface{}); ok {
		m["_response_headers"] = flat
		return m
	}
	return map[string]interface{}{
		"_result":           data,
		"_response_headers": flat,
	}
}

// outputWithHeaders marshals content to JSON, parses it, injects headers,
// and outputs in the specified format. This is the common path for --include-headers
// in json, yaml, toon, and jq output modes.
func outputWithHeaders(out io.Writer, content interface{}, headers http.Header, format, jqExpr string, colorize, jqRaw bool) error {
	// Marshal content to JSON for a uniform representation
	var parsed interface{}
	if content != nil {
		data, err := marshalJSON(content)
		if err != nil {
			return err
		}
		if err := json.Unmarshal(data, &parsed); err != nil {
			return err
		}
	}

	merged := injectHeaders(parsed, headers)

	if jqExpr != "" {
		return applyJqToTyped(out, merged, jqExpr, colorize, jqRaw)
	}

	switch format {
	case "yaml":
		yamlData, err := yaml.Marshal(merged)
		if err != nil {
			return fmt.Errorf("failed to marshal response as YAML: %w", err)
		}
		fmt.Fprint(out, string(yamlData))
	case "toon":
		toonStr, err := encodeTOON(merged)
		if err != nil {
			return fmt.Errorf("failed to encode response as TOON: %w", err)
		}
		fmt.Fprint(out, toonStr)
	default: // "json" or any other
		jsonData, err := json.MarshalIndent(merged, "", "  ")
		if err != nil {
			return err
		}
		printJSON(out, jsonData, colorize)
	}
	return nil
}

// printResponseHeadersPretty prints HTTP response headers in aligned key-value
// format, similar to prettyPrint but as a separate section.
func printResponseHeadersPretty(w io.Writer, headers http.Header, colorize bool) {
	if len(headers) == 0 {
		return
	}

	// Sort header names for stable output
	keys := make([]string, 0, len(headers))
	for k := range headers {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	// Calculate max key length for alignment
	maxKeyLen := 0
	for _, k := range keys {
		if len(k) > maxKeyLen {
			maxKeyLen = len(k)
		}
	}

	fmt.Fprintln(w)
	label := "Response Headers"
	if colorize {
		label = colorKey + label + colorReset
	}
	fmt.Fprintf(w, "%s:\n", label)
	for _, k := range keys {
		vals := headers[k]
		keyStr := k
		if colorize {
			keyStr = colorKey + k + colorReset
		}
		padding := strings.Repeat(" ", maxKeyLen-len(k))
		value := strings.Join(vals, ", ")
		if colorize {
			value = colorString + value + colorReset
		}
		fmt.Fprintf(w, "  %s:%s  %s\n", keyStr, padding, value)
	}
}

func outputJqResults(out io.Writer, results []interface{}, colorize, raw bool) error {
	for _, result := range results {
		if s, ok := result.(string); ok && raw {
			if _, err := fmt.Fprintln(out, s); err != nil {
				return err
			}
			continue
		}
		data, err := json.MarshalIndent(result, "", "  ")
		if err != nil {
			return fmt.Errorf("failed to marshal jq result: %w", err)
		}
		printJSON(out, data, colorize)
	}
	return nil
}

// applyJqToRawJSON applies a jq expression to raw JSON bytes.
func applyJqToRawJSON(out io.Writer, rawBody []byte, jqExpr string, colorize, raw bool) error {
	var data interface{}
	if err := json.Unmarshal(rawBody, &data); err != nil {
		return fmt.Errorf("failed to parse response JSON for jq: %w", err)
	}
	results, err := ApplyJqFilter(data, jqExpr)
	if err != nil {
		return err
	}
	return outputJqResults(out, results, colorize, raw)
}

// applyJqToTyped applies a jq expression to typed content (non-raw path).
func applyJqToTyped(out io.Writer, content interface{}, jqExpr string, colorize, raw bool) error {
	results, err := ApplyJqFilter(content, jqExpr)
	if err != nil {
		return err
	}
	return outputJqResults(out, results, colorize, raw)
}

// printTable renders content as an aligned table.
// For slices/arrays of structs, each struct becomes a row with struct fields as columns.
// For single structs, outputs a vertical key-value table.
// Complex nested fields are skipped.
func printTable(out io.Writer, content any) error {
	v := reflect.ValueOf(content)
	for v.Kind() == reflect.Ptr || v.Kind() == reflect.Interface {
		if v.IsNil() {
			return fmt.Errorf("nil value, nothing to display as table")
		}
		v = v.Elem()
	}

	switch v.Kind() {
	case reflect.Slice, reflect.Array:
		return printTableRows(out, v)
	case reflect.Struct:
		return printTableSingle(out, v)
	case reflect.Map:
		return printTableMap(out, v)
	default:
		// Fallback: just print the value
		fmt.Fprintln(out, v.Interface())
		return nil
	}
}

// printTableRows renders a slice of structs as a multi-row table.
func printTableRows(out io.Writer, v reflect.Value) error {
	if v.Len() == 0 {
		fmt.Fprintln(out, "(empty)")
		return nil
	}

	// Collect column info from the first element
	first := v.Index(0)
	for first.Kind() == reflect.Ptr || first.Kind() == reflect.Interface {
		if first.IsNil() {
			first = v.Index(0) // use zero value
			break
		}
		first = first.Elem()
	}
	if first.Kind() != reflect.Struct {
		// Non-struct slice: one item per line
		for i := 0; i < v.Len(); i++ {
			fmt.Fprintln(out, v.Index(i).Interface())
		}
		return nil
	}

	cols := collectTableColumns(first.Type())
	if len(cols) == 0 {
		return fmt.Errorf("no displayable columns found")
	}

	tw := newTabWriter(out)
	// Header
	headers := make([]string, len(cols))
	for i, c := range cols {
		headers[i] = strings.ToUpper(c.name)
	}
	fmt.Fprintln(tw, strings.Join(headers, "\t"))

	// Rows
	for i := 0; i < v.Len(); i++ {
		row := v.Index(i)
		for row.Kind() == reflect.Ptr || row.Kind() == reflect.Interface {
			if row.IsNil() {
				break
			}
			row = row.Elem()
		}
		if row.Kind() != reflect.Struct {
			continue
		}
		vals := make([]string, len(cols))
		for j, c := range cols {
			vals[j] = formatTableCell(row.Field(c.index))
		}
		fmt.Fprintln(tw, strings.Join(vals, "\t"))
	}
	return tw.Flush()
}

// printTableSingle renders a single struct as a vertical key-value table.
func printTableSingle(out io.Writer, v reflect.Value) error {
	cols := collectTableColumns(v.Type())
	if len(cols) == 0 {
		return fmt.Errorf("no displayable fields found")
	}

	tw := newTabWriter(out)
	for _, c := range cols {
		fmt.Fprintf(tw, "%s\t%s\n", strings.ToUpper(c.name), formatTableCell(v.Field(c.index)))
	}
	return tw.Flush()
}

// printTableMap renders a map as a two-column key-value table.
func printTableMap(out io.Writer, v reflect.Value) error {
	tw := newTabWriter(out)
	fmt.Fprintln(tw, "KEY\tVALUE")
	keys := v.MapKeys()
	sort.Slice(keys, func(i, j int) bool {
		return fmt.Sprint(keys[i].Interface()) < fmt.Sprint(keys[j].Interface())
	})
	for _, k := range keys {
		fmt.Fprintf(tw, "%v\t%s\n", k.Interface(), formatTableCell(v.MapIndex(k)))
	}
	return tw.Flush()
}

type tableColumn struct {
	name  string
	index int
}

// collectTableColumns returns the displayable (scalar) fields of a struct type.
func collectTableColumns(t reflect.Type) []tableColumn {
	var cols []tableColumn
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		// Skip complex types: structs, slices-of-structs, maps, funcs, chans
		ft := f.Type
		for ft.Kind() == reflect.Ptr {
			ft = ft.Elem()
		}
		switch ft.Kind() {
		case reflect.Struct, reflect.Map, reflect.Func, reflect.Chan:
			continue
		case reflect.Slice, reflect.Array:
			// Allow slices of primitives (e.g., []string), skip slices of structs
			elem := ft.Elem()
			for elem.Kind() == reflect.Ptr {
				elem = elem.Elem()
			}
			if elem.Kind() == reflect.Struct || elem.Kind() == reflect.Map {
				continue
			}
		}

		// Use JSON tag name if available, else field name
		name := f.Name
		if tag := f.Tag.Get("json"); tag != "" {
			parts := strings.Split(tag, ",")
			if parts[0] != "" && parts[0] != "-" {
				name = parts[0]
			}
		}
		cols = append(cols, tableColumn{name: name, index: i})
	}
	return cols
}

// formatTableCell converts a reflect.Value to a string for table display.
func formatTableCell(v reflect.Value) string {
	for v.Kind() == reflect.Ptr || v.Kind() == reflect.Interface {
		if v.IsNil() {
			return ""
		}
		v = v.Elem()
	}

	switch v.Kind() {
	case reflect.Slice, reflect.Array:
		if v.Len() == 0 {
			return ""
		}
		parts := make([]string, v.Len())
		for i := 0; i < v.Len(); i++ {
			parts[i] = fmt.Sprint(v.Index(i).Interface())
		}
		return strings.Join(parts, ", ")
	case reflect.Bool:
		if v.Bool() {
			return "true"
		}
		return "false"
	default:
		return fmt.Sprint(v.Interface())
	}
}

func newTabWriter(out io.Writer) *tabwriter.Writer {
	return tabwriter.NewWriter(out, 0, 0, 2, ' ', 0)
}
