func extractPaginationContinuation(res interface{}, probe PaginationProbe) (paginationContinuation, bool) {
	rawBody := peekRawBody(res)
	if len(rawBody) == 0 {
		return paginationContinuation{}, false
	}
	b, err := ajson.Unmarshal(rawBody)
	if err != nil {
		return paginationContinuation{}, false
	}
	if (probe.Type == "cursor" || probe.Type == "url") && probe.Results != "" {
		results, err := ajson.Eval(b, probe.Results)
		if err != nil || !results.IsArray() {
			return paginationContinuation{}, false
		}
		items, err := results.GetArray()
		if err != nil || len(items) == 0 {
			return paginationContinuation{}, false
		}
	}

	switch probe.Type {
	case "cursor":
		if probe.NextCursor == "" {
			return paginationContinuation{}, false
		}
		node, err := ajson.Eval(b, probe.NextCursor)
		if err != nil {
			return paginationContinuation{}, false
		}
		if node.IsNumeric() {
			value, err := node.GetNumeric()
			if err != nil {
				return paginationContinuation{}, false
			}
			// Key on the value the SDK sends: it truncates numeric cursors for string and integer kinds.
			var formatted string
			switch probe.CursorKind {
			case "string":
				formatted = strconv.FormatFloat(value, 'f', 0, 64)
			case "integer":
				formatted = strconv.FormatInt(int64(value), 10)
			default:
				formatted = strconv.FormatFloat(value, 'g', -1, 64)
			}
			return paginationContinuation{
				key:     "cursor:number:" + formatted,
				kind:    "cursor",
				display: formatted,
			}, true
		}
		if !node.IsString() {
			return paginationContinuation{}, false
		}
		value, err := node.GetString()
		if err != nil || strings.TrimSpace(value) == "" {
			return paginationContinuation{}, false
		}
		return paginationContinuation{
			key:     "cursor:string:" + value,
			kind:    "cursor",
			display: strconv.Quote(value),
		}, true

	case "url":
		if probe.NextURL == "" {
			return paginationContinuation{}, false
		}
		node, err := ajson.Eval(b, probe.NextURL)
		if err != nil || !node.IsString() {
			return paginationContinuation{}, false
		}
		value, err := node.GetString()
		if err != nil || value == "" {
			return paginationContinuation{}, false
		}
		return paginationContinuation{
			key:     "url:" + value,
			kind:    "URL",
			display: strconv.Quote(value),
		}, true
	}

	return paginationContinuation{}, false
}

// callNext invokes the Next() pagination closure on a response envelope via reflection.
// Returns (nextRes, nil) on success, (nil, nil) when pagination is complete, or (nil, err) on failure.
func callNext(res interface{}) (interface{}, error) {
	v := reflect.ValueOf(res)
	if v.Kind() == reflect.Ptr {
		if v.IsNil() {
			return nil, nil
		}
		v = v.Elem()
	}
	if v.Kind() != reflect.Struct {
		return nil, nil
	}
	nextField := v.FieldByName("Next")
	if !nextField.IsValid() || nextField.Kind() != reflect.Func || nextField.IsNil() {
		return nil, nil
	}
	// Next() signature is func() (*T, error)
	results := nextField.Call(nil)
	if len(results) != 2 {
		return nil, fmt.Errorf("unexpected Next() return count: %d", len(results))
	}
	if !results[1].IsNil() {
		if err, ok := results[1].Interface().(error); ok {
			return nil, err
		}
		return nil, fmt.Errorf("Next() returned non-error second value: %v", results[1].Interface())
	}
	if results[0].IsNil() {
		return nil, nil
	}
	return results[0].Interface(), nil
}

// HasMorePages never calls Next; offset/limit probes always report false.
func HasMorePages(res interface{}, probe PaginationProbe) bool {
	// Next also compares the results length with the runtime limit, which the probe lacks.
	if probe.Results != "" && probe.HasLimit {
		return false
	}
	_, ok := extractPaginationContinuation(res, probe)
	return ok
}

// extractFieldByPath navigates a reflect.Value by dot-delimited Go field names.
// Returns an invalid reflect.Value if any segment is not found or nil.
func extractFieldByPath(v reflect.Value, path string) reflect.Value {
	parts := strings.Split(path, ".")
	current := v
	for _, part := range parts {
		for current.Kind() == reflect.Ptr || current.Kind() == reflect.Interface {
			if current.IsNil() {
				return reflect.Value{}
			}
			current = current.Elem()
		}
		if current.Kind() != reflect.Struct {
			return reflect.Value{}
		}
		current = current.FieldByName(part)
		if !current.IsValid() {
			return reflect.Value{}
		}
	}
	return current
}
