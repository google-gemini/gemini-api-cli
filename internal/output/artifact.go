func artifactOutPath(path, ext string) (string, bool) {
	if ext == "" {
		return path, false
	}
	currentExt := strings.TrimPrefix(strings.ToLower(filepath.Ext(path)), ".")
	if currentExt == ext {
		return path, false
	}
	current, known := artifactMediaExtensions[currentExt]
	if !known {
		return strings.TrimSuffix(path, ".") + "." + ext, false
	}
	returned, known := artifactMediaExtensions[ext]
	return path, known && current != returned
}

func writeArtifactDefault(dir string, payload []byte, ext string, cfg *artifactConfig) (string, error) {
	if ext == "" {
		ext = artifactKindFallbackExt(cfg.Kind)
	}
	name := cfg.DefaultPath
	name = strings.ReplaceAll(name, "{timestamp}", time.Now().Format("20060102-150405"))
	name = strings.ReplaceAll(name, "{rand}", artifactRandSuffix())
	name = strings.ReplaceAll(name, "{ext}", ext)
	base := filepath.Join(dir, filepath.FromSlash(name))
	if parent := filepath.Dir(base); parent != "." {
		if err := os.MkdirAll(parent, 0o755); err != nil {
			return "", fmt.Errorf("cannot create output directory %s: %w", parent, err)
		}
	}

	extPart := filepath.Ext(base)
	stem := strings.TrimSuffix(base, extPart)
	for i := 0; i < 1000; i++ {
		candidate := base
		if i > 0 {
			candidate = fmt.Sprintf("%s-%d%s", stem, i+1, extPart)
		}
		f, err := os.OpenFile(candidate, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
		if err != nil {
			if os.IsExist(err) {
				continue
			}
			return "", fmt.Errorf("cannot create %s: %w", candidate, err)
		}
		if _, err := f.Write(payload); err != nil {
			f.Close()
			os.Remove(candidate)
			return "", fmt.Errorf("cannot write %s: %w", candidate, err)
		}
		if err := f.Close(); err != nil {
			os.Remove(candidate)
			return "", fmt.Errorf("cannot write %s: %w", candidate, err)
		}
		return candidate, nil
	}
	return "", fmt.Errorf("could not find a collision-free filename near %s", base)
}

func artifactAtomicReplace(path string, payload []byte) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, ".artifact-*")
	if err != nil {
		return fmt.Errorf("cannot create %s: %w", path, err)
	}
	tmpName := tmp.Name()
	cleanup := func() { os.Remove(tmpName) }
	if _, err := tmp.Write(payload); err != nil {
		tmp.Close()
		cleanup()
		return fmt.Errorf("cannot write %s: %w", path, err)
	}
	// chmod through the descriptor, not the path (symlink swap).
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		cleanup()
		return fmt.Errorf("cannot write %s: %w", path, err)
	}
	if err := tmp.Close(); err != nil {
		cleanup()
		return fmt.Errorf("cannot write %s: %w", path, err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		cleanup()
		return fmt.Errorf("cannot write %s: %w", path, err)
	}
	return nil
}

func artifactExtension(kind, mimeType string) string {
	base := strings.ToLower(strings.TrimSpace(strings.Split(mimeType, ";")[0]))
	if base == "" {
		return ""
	}
	top, sub, ok := strings.Cut(base, "/")
	if !ok || top != kind {
		return ""
	}
	sub, _, _ = strings.Cut(strings.TrimPrefix(strings.TrimPrefix(sub, "x-"), "vnd."), "+")
	if ext, ok := artifactMimeExtensions[top+"/"+sub]; ok {
		return ext
	}
	var b strings.Builder
	for _, r := range sub {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
		}
	}
	return b.String()
}

func artifactKindFallbackExt(kind string) string {
	switch kind {
	case "audio":
		return "wav"
	case "video":
		return "mp4"
	default:
		return "jpg"
	}
}

func artifactRandSuffix() string {
	var buf [8]byte
	if _, err := rand.Read(buf[:]); err != nil {
		return fmt.Sprintf("%06d", time.Now().Nanosecond()%1000000)
	}
	v := binary.BigEndian.Uint64(buf[:])
	const alphabet = "abcdefghijklmnopqrstuvwxyz0123456789"
	out := make([]byte, 6)
	for i := range out {
		out[i] = alphabet[v%36]
		v /= 36
	}
	return string(out)
}
