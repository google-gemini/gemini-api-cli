func artifactCandidates(node interface{}, segs []artifactSegment) []interface{} {
	if len(segs) == 0 {
		return []interface{}{node}
	}
	seg := segs[0]
	if seg.Wild {
		arr, ok := node.([]interface{})
		if !ok {
			return nil
		}
		var out []interface{}
		for _, item := range arr {
			out = append(out, artifactCandidates(item, segs[1:])...)
		}
		return out
	}
	m, ok := node.(map[string]interface{})
	if !ok {
		return nil
	}
	child, ok := m[seg.Field]
	if !ok {
		return nil
	}
	return artifactCandidates(child, segs[1:])
}

// findArtifactItem returns the last block of the configured kind in document
// order. Selection is by kind, not payload: a trailing URI-only or data-less
// block is returned, and the caller downloads or reports it, rather than an
// earlier block.
func findArtifactItem(parsed interface{}, cfg *artifactConfig) map[string]interface{} {
	candidates := artifactCandidates(parsed, cfg.Pointer)
	for i := len(candidates) - 1; i >= 0; i-- {
		m, ok := candidates[i].(map[string]interface{})
		if !ok {
			continue
		}
		if t, _ := m[cfg.TypeField].(string); t == cfg.Kind {
			return m
		}
	}
	return nil
}

func artifactMissingError(cfg *artifactConfig, parsed interface{}) error {
	msg := fmt.Sprintf("the response contained no %s content to write", cfg.Kind)
	if m, ok := parsed.(map[string]interface{}); ok {
		status, _ := m[cfg.StatusField].(string)
		id, _ := m[cfg.IDField].(string)
		if status != "" && status != cfg.TerminalStatus {
			msg += fmt.Sprintf(" (status %q", status)
			if id != "" {
				msg += fmt.Sprintf(", id %q", id)
			}
			msg += " — the result may not be ready yet)"
		}
	}
	return fmt.Errorf("%s", msg)
}

func decodeArtifactBase64(s string) ([]byte, error) {
	s = strings.TrimSpace(s)
	var firstErr error
	for _, enc := range []*base64.Encoding{
		base64.StdEncoding, base64.RawStdEncoding, base64.URLEncoding, base64.RawURLEncoding,
	} {
		decoded, err := enc.DecodeString(s)
		if err == nil {
			return decoded, nil
		}
		if firstErr == nil {
			firstErr = err
		}
	}
	return nil, firstErr
}

func writeArtifact(outFlag string, payload []byte, mimeType string, cfg *artifactConfig) (string, bool, error) {
	ext := artifactExtension(cfg.Kind, mimeType)

	if outFlag == "" {
		path, err := writeArtifactDefault("", payload, ext, cfg)
		return path, false, err
	}

	info, statErr := os.Stat(outFlag)
	endsWithSep := strings.HasSuffix(outFlag, "/") || strings.HasSuffix(outFlag, string(os.PathSeparator))
	if (statErr == nil && info.IsDir()) || (statErr != nil && endsWithSep) {
		if statErr != nil {
			if err := os.MkdirAll(outFlag, 0o755); err != nil {
				return "", false, fmt.Errorf("cannot create output directory %s: %w", outFlag, err)
			}
		}
		path, err := writeArtifactDefault(outFlag, payload, ext, cfg)
		return path, false, err
	}

	finalPath, mismatch := artifactOutPath(outFlag, ext)
	if dir := filepath.Dir(finalPath); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return "", false, fmt.Errorf("cannot create output directory %s: %w", dir, err)
		}
	}
	if err := artifactAtomicReplace(finalPath, payload); err != nil {
		return "", false, err
	}
	return finalPath, mismatch, nil
}

