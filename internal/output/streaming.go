// Case-sensitive: undiscriminated unions put PascalCase variant names ("ErrorEvent") in Type.
func isErrorDiscriminator(value string) bool {
	if value == "error" {
		return true
	}
	return strings.HasSuffix(value, ".error") || strings.HasSuffix(value, "_error") || strings.HasSuffix(value, "-error")
}

// isNillable returns true if IsNil() can be safely called on v.
