// ContinuationStream streams the response, then opens the next hop's stream
// with the resume values seen in the events while the last reported state
// classifies as continue. Every hop's events go to one output sequence.
func ContinuationStream(cmd *cobra.Command, request interface{}, hop ContinuationHop, streamFieldName string) error {
	run, err := newContinuationRun(cmd, request, hop)
	if err != nil {
		return err
	}
	if len(run.outcome.streamStatePointers()) == 0 {
		res, err := run.send()
		if err != nil {
			return Error(cmd, err)
		}
		return StreamResult(cmd, res, streamFieldName)
	}
	res, err := run.send()
	if err != nil {
		return Error(cmd, err)
	}
	run.beginHop()
	hops := &streamContinuation{run: run}
	if err := streamResult(cmd, res, streamFieldName, hops, nil); err != nil || hops.finished {
		return err
	}
	return run.finish()
}

type streamContinuation struct {
	run      *continuationRun
	finished bool
}

func (s *streamContinuation) discrete(res interface{}) error {
	s.finished = true
	return s.run.discrete(res)
}

func (s *streamContinuation) observe(frame map[string]interface{}) {
	if frame != nil {
		s.run.capture(frame, true)
	}
}

func (s *streamContinuation) wrap(err error) error { return s.run.wrap(err) }

func (s *streamContinuation) next() (interface{}, bool, error) {
	switch s.run.outcome.States[s.run.state] {
	case "continue", "success", "failure", "handoff":
	default:
		if s.run.resumable() {
			message := "the stream ended before reporting a final state"
			if s.run.state != "" {
				message = fmt.Sprintf("the stream ended while the response was still %q", s.run.state)
			}
			return nil, false, s.run.wrap(WithCLIReason(errors.New(message), ReasonCLIConnection))
		}
	}
	more, err := s.run.advance()
	if err != nil || !more {
		return nil, false, err
	}
	res, err := s.run.send()
	if err != nil {
		return nil, false, err
	}
	s.run.beginHop()
	return res, true, nil
}
