// ContinuationResult sends the request, then re-sends it with the resume
// values from each response while the response's state classifies as
// continue, and renders one result.
func ContinuationResult(cmd *cobra.Command, request interface{}, hop ContinuationHop) error {
	run, err := newContinuationRun(cmd, request, hop)
	if err != nil {
		return err
	}
	res, err := run.send()
	if err != nil {
		return Error(cmd, err)
	}
	if run.skipped {
		return Result(cmd, res)
	}
	return run.discrete(res)
}

// discrete continues from an already-sent response whose body is a single
// JSON document.
func (r *continuationRun) discrete(res interface{}) error {
	cmd, run := r.cmd, r
	var (
		last     interface{}
		payloads []interface{}
	)
	for {
		if len(payloads) > 0 {
			var err error
			if res, err = run.send(); err != nil {
				return Error(cmd, err)
			}
		}
		if flagutil.DidDryRunRequest(cmd) {
			return Result(cmd, res)
		}
		payload, ok := outcomeResultPayload(res)
		if !ok {
			return Result(cmd, res)
		}
		last = res
		payloads = append(payloads, payload)
		run.beginHop()
		run.capture(payload, false)
		more, err := run.advance()
		if err != nil {
			return Error(cmd, err)
		}
		if !more {
			break
		}
	}

	target := last
	if run.combines(len(payloads)) {
		target = mergedContinuationResult(last, mergeContinuationPayloads(run.cfg, payloads))
	}
	if failure := outcomeResultFailure(cmd, target); failure != nil {
		if activeArtifact(cmd) != nil {
			return Error(cmd, run.wrap(failure))
		}
		if err := renderResult(cmd, target, true); err != nil {
			return err
		}
		return Error(cmd, run.wrap(failure))
	}
	if err := Result(cmd, target); err != nil {
		return err
	}
	return run.finish()
}

// combines leaves a single auto-continued response as sent unless the recipe
// adds fields to it, so one-hop results match multi-hop ones.
func (r *continuationRun) combines(hops int) bool {
	cfg := r.cfg
	if !r.auto || hops == 0 {
		return false
	}
	if len(cfg.Collect) > 0 {
		return true
	}
	for _, kept := range cfg.KeepFirst {
		if kept.Fallback != "" {
			return true
		}
	}
	return hops > 1 && (len(cfg.Merge) > 0 || len(cfg.Sum) > 0 || len(cfg.KeepFirst) > 0 || len(cfg.SumBy) > 0)
}

func mergeContinuationPayloads(cfg *continuationConfig, payloads []interface{}) interface{} {
	first := payloads[0]
	merged := cloneContinuationJSON(payloads[len(payloads)-1])
	for _, pointer := range cfg.Merge {
		var drop *continuationMergeDrop
		for i := range cfg.MergeDropLeadingWhere {
			if cfg.MergeDropLeadingWhere[i].Pointer == pointer {
				drop = &cfg.MergeDropLeadingWhere[i]
			}
		}
		var items []interface{}
		found := false
		for i, payload := range payloads {
			if value, ok := outcomePointer(payload, pointer); ok {
				if list, isList := value.([]interface{}); isList {
					if i > 0 && drop != nil {
						list = dropContinuationLeading(list, drop)
					}
					items = append(items, cloneContinuationJSON(list).([]interface{})...)
					found = true
				}
			}
		}
		if found {
			if items == nil {
				items = []interface{}{}
			}
			merged = setContinuationPointer(merged, pointer, items)
		}
	}
	for _, kept := range cfg.KeepFirst {
		value, ok := outcomePointer(first, kept.Pointer)
		if (!ok || value == nil) && kept.Fallback != "" {
			if fallback, found := outcomePointer(first, kept.Fallback); found && fallback != nil {
				value, ok = fallback, true
			}
		}
		switch {
		case ok && value != nil:
			parent := continuationParentPointer(kept.Pointer)
			_, firstHasParent := continuationObjectAt(first, parent)
			_, mergedHasParent := continuationObjectAt(merged, parent)
			if firstHasParent || mergedHasParent {
				merged = setContinuationPointer(merged, kept.Pointer, cloneContinuationJSON(value))
			}
		case len(payloads) > 1:
			deleteContinuationPointer(merged, kept.Pointer)
		}
	}
	for _, collect := range cfg.Collect {
		if values := collectContinuationStrings(payloads, collect); len(values) > 0 {
			merged = setContinuationPointer(merged, collect.To, values)
		}
	}
	for _, pointer := range cfg.Sum {
		if total, ok := sumContinuationValues(payloads, pointer); ok {
			merged = setContinuationPointer(merged, pointer, total)
		}
	}
	for _, rule := range cfg.SumBy {
		if items, ok := sumContinuationGroups(payloads, rule); ok {
			merged = setContinuationPointer(merged, rule.Pointer, items)
		}
	}
	return merged
}

func dropContinuationLeading(items []interface{}, drop *continuationMergeDrop) []interface{} {
	for len(items) > 0 {
		object, ok := items[0].(map[string]interface{})
		if !ok {
			break
		}
		value, present := object[drop.Field]
		if !present || !continuationValuesEqual(value, drop.Equals) {
			break
		}
		items = items[1:]
	}
	return items
}

func collectContinuationStrings(payloads []interface{}, collect continuationCollect) []interface{} {
	var values []interface{}
	seen := map[string]bool{}
	add := func(value interface{}) {
		text, ok := value.(string)
		if !ok || text == "" || (collect.Unique && seen[text]) {
			return
		}
		seen[text] = true
		values = append(values, text)
	}
	for _, payload := range payloads {
		for _, pointer := range collect.From {
			value, ok := outcomePointer(payload, pointer)
			if !ok {
				continue
			}
			if list, isList := value.([]interface{}); isList {
				for _, item := range list {
					add(item)
				}
				continue
			}
			add(value)
		}
	}
	return values
}

type continuationGroup struct {
	item       map[string]interface{}
	total      *big.Rat
	summed     bool
	unsummable bool
}

// sumContinuationGroups keeps items that are not objects with a scalar key
// as they are.
func sumContinuationGroups(payloads []interface{}, rule continuationSumBy) ([]interface{}, bool) {
	var entries []interface{}
	groups := map[string]*continuationGroup{}
	found := false
	for _, payload := range payloads {
		value, ok := outcomePointer(payload, rule.Pointer)
		list, isList := value.([]interface{})
		if !ok || !isList {
			continue
		}
		found = true
		for _, element := range list {
			object, isObject := element.(map[string]interface{})
			var key interface{}
			if isObject {
				key = object[rule.Key]
			}
			id, groupable := continuationGroupKey(key)
			if !groupable {
				entries = append(entries, cloneContinuationJSON(element))
				continue
			}
			group := groups[id]
			if group == nil {
				group = &continuationGroup{item: cloneContinuationJSON(object).(map[string]interface{}), total: new(big.Rat)}
				groups[id] = group
				entries = append(entries, group)
			}
			if number, ok := continuationNumber(object[rule.Value]); ok {
				group.total.Add(group.total, number)
				group.summed = true
			} else if _, isNumber := object[rule.Value].(json.Number); isNumber {
				group.unsummable = true
			}
		}
	}
	if !found {
		return nil, false
	}
	items := make([]interface{}, 0, len(entries))
	for _, entry := range entries {
		group, isGroup := entry.(*continuationGroup)
		if !isGroup {
			items = append(items, entry)
			continue
		}
		if group.summed && !group.unsummable {
			group.item[rule.Value] = continuationTotal(group.total)
		}
		items = append(items, group.item)
	}
	return items, true
}

func continuationGroupKey(key interface{}) (string, bool) {
	switch typed := key.(type) {
	case string:
		return "s" + typed, true
	case bool:
		return "b" + strconv.FormatBool(typed), true
	}
	if number, ok := continuationNumber(key); ok {
		return "n" + number.RatString(), true
	}
	return "", false
}

func sumContinuationValues(payloads []interface{}, pointer string) (json.Number, bool) {
	total := new(big.Rat)
	found := false
	for _, payload := range payloads {
		value, ok := outcomePointer(payload, pointer)
		if !ok {
			continue
		}
		number, isNumber := value.(json.Number)
		if !isNumber {
			continue
		}
		term, ok := continuationNumber(number)
		if !ok {
			return "", false
		}
		total.Add(total, term)
		found = true
	}
	if !found {
		return "", false
	}
	return continuationTotal(total), true
}

func continuationTotal(total *big.Rat) json.Number {
	if total.IsInt() {
		return json.Number(total.Num().String())
	}
	approx, _ := total.Float64()
	return json.Number(strconv.FormatFloat(approx, 'g', -1, 64))
}

func cloneContinuationJSON(value interface{}) interface{} {
	switch typed := value.(type) {
	case map[string]interface{}:
		cloned := make(map[string]interface{}, len(typed))
		for key, child := range typed {
			cloned[key] = cloneContinuationJSON(child)
		}
		return cloned
	case []interface{}:
		cloned := make([]interface{}, len(typed))
		for i, child := range typed {
			cloned[i] = cloneContinuationJSON(child)
		}
		return cloned
	default:
		return value
	}
}

func continuationPointerTokens(pointer string) []string {
	if !strings.HasPrefix(pointer, "/") {
		return nil
	}
	var tokens []string
	for _, raw := range strings.Split(strings.TrimPrefix(pointer, "/"), "/") {
		tokens = append(tokens, strings.ReplaceAll(strings.ReplaceAll(raw, "~1", "/"), "~0", "~"))
	}
	return tokens
}

func continuationParentPointer(pointer string) string {
	if index := strings.LastIndex(pointer, "/"); index > 0 {
		return pointer[:index]
	}
	return ""
}

func continuationObjectAt(root interface{}, pointer string) (map[string]interface{}, bool) {
	value, ok := outcomePointer(root, pointer)
	object, isObject := value.(map[string]interface{})
	return object, ok && isObject
}

func setContinuationPointer(root interface{}, pointer string, value interface{}) interface{} {
	tokens := continuationPointerTokens(pointer)
	object, ok := root.(map[string]interface{})
	if len(tokens) == 0 || !ok {
		return root
	}
	current := object
	for _, token := range tokens[:len(tokens)-1] {
		child, ok := current[token].(map[string]interface{})
		if !ok {
			child = map[string]interface{}{}
			current[token] = child
		}
		current = child
	}
	current[tokens[len(tokens)-1]] = value
	return object
}

func deleteContinuationPointer(root interface{}, pointer string) {
	tokens := continuationPointerTokens(pointer)
	if len(tokens) == 0 {
		return
	}
	parent, ok := continuationObjectAt(root, continuationParentPointer(pointer))
	if ok {
		delete(parent, tokens[len(tokens)-1])
	}
}

type continuationHTTPMeta struct {
	Response *http.Response
}

type continuationResultEnvelope struct {
	HTTPMeta continuationHTTPMeta
	Result   interface{}
}

func mergedContinuationResult(last interface{}, merged interface{}) interface{} {
	raw, err := json.Marshal(merged)
	if err != nil {
		return last
	}
	var resp http.Response
	if lastResp := extractHTTPResponse(last); lastResp != nil {
		resp = *lastResp
		resp.Header = lastResp.Header.Clone()
	}
	resp.Body = io.NopCloser(bytes.NewReader(raw))
	resp.ContentLength = int64(len(raw))
	return &continuationResultEnvelope{
		HTTPMeta: continuationHTTPMeta{Response: &resp},
		Result:   merged,
	}
}

func continuationRequestPayload(request interface{}) interface{} {
	target, err := continuationBodyTarget(request)
	if err != nil {
		return nil
	}
	encoded, err := json.Marshal(target.Interface())
	if err != nil {
		return nil
	}
	payload, err := decodeWithNumbers(encoded)
	if err != nil {
		return nil
	}
	return payload
}

type continuationBodySet struct {
	to    string
	path  []string
	value string
}

// updateContinuationBody edits the request field tagged as the media-type
// body, or the request itself when the body is the whole request. The body
// round-trips through JSON so nested paths and union bodies are written the
// way the API receives them.
func updateContinuationBody(request interface{}, sets []continuationBodySet, omits [][]string) error {
	if len(sets) == 0 && len(omits) == 0 {
		return nil
	}
	target, err := continuationBodyTarget(request)
	if err != nil {
		return err
	}
	if target.Kind() == reflect.Ptr && target.IsNil() {
		target.Set(reflect.New(target.Type().Elem()))
	}
	encoded, err := json.Marshal(target.Interface())
	if err != nil {
		return err
	}
	decoded, err := decodeWithNumbers(encoded)
	if err != nil {
		return err
	}
	body, ok := decoded.(map[string]interface{})
	if !ok {
		return errors.New("the request body is not a JSON object")
	}
	for _, set := range sets {
		flagutil.SetBodyPath(body, set.path, set.value)
	}
	for _, path := range omits {
		deleteContinuationBodyPath(body, path)
	}
	encoded, err = json.Marshal(body)
	if err != nil {
		return err
	}
	fresh := reflect.New(target.Type())
	if err := json.Unmarshal(encoded, fresh.Interface()); err != nil {
		return err
	}
	target.Set(fresh.Elem())
	return nil
}

func deleteContinuationBodyPath(body map[string]interface{}, path []string) {
	if len(path) == 0 {
		return
	}
	current := body
	for _, key := range path[:len(path)-1] {
		child, ok := current[key].(map[string]interface{})
		if !ok {
			return
		}
		current = child
	}
	delete(current, path[len(path)-1])
}

func continuationBodyTarget(request interface{}) (reflect.Value, error) {
	v := reflect.ValueOf(request)
	if v.Kind() != reflect.Ptr || v.IsNil() {
		return reflect.Value{}, errors.New("the request must be passed by pointer")
	}
	v = v.Elem()
	s := v
	for s.Kind() == reflect.Ptr && !s.IsNil() {
		s = s.Elem()
	}
	if s.Kind() == reflect.Struct {
		for i := 0; i < s.NumField(); i++ {
			if strings.HasPrefix(s.Type().Field(i).Tag.Get("request"), "mediaType=") && s.Field(i).CanSet() {
				return s.Field(i), nil
			}
		}
	}
	return v, nil
}

// ContinuationStream streams the response, then opens the next hop's stream
// with the resume values seen in the events while the last reported state
// classifies as continue. Every hop's events go to one output sequence.
func ContinuationStream(cmd *cobra.Command, request interface{}, hop ContinuationHop, streamFieldName string) error {
	run, err := newContinuationRun(cmd, request, hop)
	if err != nil {
		return err
	}
	if run.skipped || len(run.outcome.streamStatePointers()) == 0 {
		res, err := run.send()
		if err != nil {
			return Error(cmd, err)
		}
		return StreamResult(cmd, res, streamFieldName)
	}
	res, err := run.send()
	if err != nil {
		return Error(cmd, err)
	}
	run.beginHop()
	hops := &streamContinuation{run: run}
	if err := streamResult(cmd, res, streamFieldName, hops, nil); err != nil || hops.finished {
		return err
	}
	return run.finish()
}

type streamContinuation struct {
	run      *continuationRun
	finished bool
}

func (s *streamContinuation) discrete(res interface{}) error {
	s.finished = true
	return s.run.discrete(res)
}

func (s *streamContinuation) observe(frame map[string]interface{}) {
	if frame != nil {
		s.run.capture(frame, true)
	}
}

// abort discards the values captured in a stream the server ended with an
// error event, so a resume points at the last hop that completed.
func (s *streamContinuation) abort() {
	s.run.state = ""
	s.run.values = map[string]string{}
}

func (s *streamContinuation) wrap(err error) error { return s.run.wrap(err) }

func (s *streamContinuation) next() (interface{}, bool, error) {
	switch s.run.outcome.States[s.run.state] {
	case "continue", "success", "failure", "handoff":
	default:
		if s.run.resumable() {
			message := "the stream ended before reporting a final state"
			if s.run.state != "" {
				message = fmt.Sprintf("the stream ended while the response was still %q", s.run.state)
			}
			return nil, false, s.run.wrap(WithCLIReason(errors.New(message), ReasonCLIConnection))
		}
	}
	more, err := s.run.advance()
	if err != nil || !more {
		return nil, false, err
	}
	res, err := s.run.send()
	if err != nil {
		return nil, false, err
	}
	s.run.beginHop()
	return res, true, nil
}
