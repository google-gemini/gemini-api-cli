func (r *continuationRun) resumeValues() map[string]string {
	if r.outcome.States[r.state] == "success" || r.outcome.States[r.state] == "handoff" {
		return nil
	}
	if r.outcome.States[r.state] == "failure" || len(r.values) == 0 || !r.hasCompleteRequiredBindings(r.values) || (r.repeated() && r.fallbackValid) {
		if r.fallbackValid {
			return r.fallback
		}
		return nil
	}
	return r.values
}

func cloneContinuationValues(values map[string]string) map[string]string {
	cloned := make(map[string]string, len(values))
	for key, value := range values {
		cloned[key] = value
	}
	return cloned
}

// resumeHint names the command's own flags for each resume value; values
// without a declared flag are named by their request-body path.
func (r *continuationRun) resumeHint() string {
	if !r.resumable() {
		return ""
	}
	var flags, paths []string
	values := r.resumeValues()
	for _, binding := range r.cfg.Bind {
		if !r.bindingEnabled(binding) {
			continue
		}
		value, ok := values[binding.To]
		if !ok {
			continue
		}
		if binding.Flag != "" {
			flags = append(flags, fmt.Sprintf("--%s %s", binding.Flag, strconv.Quote(value)))
		} else {
			paths = append(paths, fmt.Sprintf("%s=%s", binding.To, strconv.Quote(value)))
		}
	}
	var parts []string
	if len(flags) > 0 {
		parts = append(parts, "re-run the same command with "+strings.Join(flags, " "))
	}
	if len(paths) > 0 {
		parts = append(parts, "set "+strings.Join(paths, ", ")+" in the request body")
	}
	hint := "To continue, " + strings.Join(parts, " and ")
	var omitted []string
	for _, omit := range r.cfg.Omit {
		if r.omitEnabled(omit) && omit.Name != "" {
			omitted = append(omitted, omit.Name)
		}
	}
	if len(omitted) > 0 {
		hint += ", leaving " + strings.Join(omitted, ", ") + " out of the request body"
	}
	return hint
}

func (r *continuationRun) wrap(err error) error {
	if err == nil {
		return nil
	}
	return &continuationError{err: err, hops: r.hops, resume: r.resumeFields(), hint: r.resumeHint()}
}

// finish reports what the loop stopped on once the result is rendered.
func (r *continuationRun) finish() error {
	if r.limited {
		return Error(r.cmd, &continuationLimitError{hops: r.hops, resume: r.resumeFields(), hint: r.resumeHint()})
	}
	if len(r.missing) > 0 {
		sort.Strings(r.missing)
		return Error(r.cmd, r.wrap(WithCLIReason(fmt.Errorf("the response reported state %q but carried no %s to continue with; the output is incomplete", r.state, strings.Join(r.missing, ", ")), ReasonCLIProtocol)))
	}
	if IsMachineMode(r.cmd) || r.cmd.Context().Err() != nil {
		return nil
	}
	stderr := r.cmd.ErrOrStderr()
	if r.hops > 1 {
		fmt.Fprintf(stderr, "Continued across %d responses.\n", r.hops)
	}
	if r.stalled {
		fmt.Fprintln(stderr, "Stopped continuing: the response returned the resume value it was sent with.")
	}
	if r.outcome.States[r.state] == "continue" && !r.auto {
		if hint := r.resumeHint(); hint != "" {
			fmt.Fprintln(stderr, hint+".")
		}
	}
	return nil
}

