func continuationValuesEqual(left, right interface{}) bool {
	if reflect.DeepEqual(left, right) {
		return true
	}
	leftNumber, leftOK := continuationNumber(left)
	rightNumber, rightOK := continuationNumber(right)
	return leftOK && rightOK && leftNumber.Cmp(rightNumber) == 0
}

