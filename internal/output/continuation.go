// finish reports what the loop stopped on once the result is rendered.
func (r *continuationRun) finish() error {
	if r.limited {
		return Error(r.cmd, &continuationLimitError{hops: r.hops, resume: r.resumeFields(), hint: r.resumeHint()})
	}
	if len(r.missing) > 0 {
		sort.Strings(r.missing)
		return Error(r.cmd, r.wrap(WithCLIReason(fmt.Errorf("the response reported state %q but carried no %s to continue with; the output is incomplete", r.state, strings.Join(r.missing, ", ")), ReasonCLIProtocol)))
	}
	if IsMachineMode(r.cmd) || r.cmd.Context().Err() != nil {
		return nil
	}
	stderr := r.cmd.ErrOrStderr()
	if r.hops > 1 {
		fmt.Fprintf(stderr, "Continued across %d responses.\n", r.hops)
	}
	if r.outcome.States[r.state] == "continue" && !r.auto {
		if hint := r.resumeHint(); hint != "" {
			fmt.Fprintln(stderr, hint+".")
		}
	}
	return nil
}

