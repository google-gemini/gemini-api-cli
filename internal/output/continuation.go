// ContinuationResult sends the request, then re-sends it with the resume
// values from each response while the response's state classifies as
// continue, and renders one result.
func ContinuationResult(cmd *cobra.Command, request interface{}, hop ContinuationHop) error {
	run, err := newContinuationRun(cmd, request, hop)
	if err != nil {
		return err
	}
	res, err := run.send()
	if err != nil {
		return Error(cmd, err)
	}
	return run.discrete(res)
}

// discrete continues from an already-sent response whose body is a single
// JSON document.
func (r *continuationRun) discrete(res interface{}) error {
	cmd, run := r.cmd, r
	var (
		last     interface{}
		payloads []interface{}
	)
	for {
		if len(payloads) > 0 {
			var err error
			if res, err = run.send(); err != nil {
				return Error(cmd, err)
			}
		}
		if flagutil.DidDryRunRequest(cmd) {
			return Result(cmd, res)
		}
		payload, ok := outcomeResultPayload(res)
		if !ok {
			return Result(cmd, res)
		}
		last = res
		payloads = append(payloads, payload)
		run.beginHop()
		run.capture(payload, false)
		more, err := run.advance()
		if err != nil {
			return Error(cmd, err)
		}
		if !more {
			break
		}
	}

	target := last
	if len(payloads) > 1 && (len(run.cfg.Merge) > 0 || len(run.cfg.Sum) > 0) {
		target = mergedContinuationResult(last, mergeContinuationPayloads(run.cfg, payloads))
	}
	if failure := outcomeResultFailure(cmd, target); failure != nil {
		if activeArtifact(cmd) != nil {
			return Error(cmd, run.wrap(failure))
		}
		if err := renderResult(cmd, target, true); err != nil {
			return err
		}
		return Error(cmd, run.wrap(failure))
	}
	if err := Result(cmd, target); err != nil {
		return err
	}
	return run.finish()
}

func mergeContinuationPayloads(cfg *continuationConfig, payloads []interface{}) interface{} {
	merged := payloads[len(payloads)-1]
	for _, pointer := range cfg.Merge {
		var items []interface{}
		found := false
		for _, payload := range payloads {
			if value, ok := outcomePointer(payload, pointer); ok {
				if list, isList := value.([]interface{}); isList {
					items = append(items, list...)
					found = true
				}
			}
		}
		if found {
			merged = setContinuationPointer(merged, pointer, items)
		}
	}
	for _, pointer := range cfg.Sum {
		if total, ok := sumContinuationValues(payloads, pointer); ok {
			merged = setContinuationPointer(merged, pointer, total)
		}
	}
	return merged
}

func sumContinuationValues(payloads []interface{}, pointer string) (json.Number, bool) {
	total := new(big.Rat)
	found := false
	for _, payload := range payloads {
		value, ok := outcomePointer(payload, pointer)
		if !ok {
			continue
		}
		number, isNumber := value.(json.Number)
		if !isNumber {
			continue
		}
		term, ok := new(big.Rat).SetString(number.String())
		if !ok {
			continue
		}
		total.Add(total, term)
		found = true
	}
	if !found {
		return "", false
	}
	if total.IsInt() {
		return json.Number(total.Num().String()), true
	}
	approx, _ := total.Float64()
	return json.Number(strconv.FormatFloat(approx, 'g', -1, 64)), true
}

func setContinuationPointer(root interface{}, pointer string, value interface{}) interface{} {
	if !strings.HasPrefix(pointer, "/") {
		return root
	}
	var tokens []string
	for _, raw := range strings.Split(strings.TrimPrefix(pointer, "/"), "/") {
		tokens = append(tokens, strings.ReplaceAll(strings.ReplaceAll(raw, "~1", "/"), "~0", "~"))
	}
	object, ok := root.(map[string]interface{})
	if !ok {
		return root
	}
	current := object
	for _, token := range tokens[:len(tokens)-1] {
		child, ok := current[token].(map[string]interface{})
		if !ok {
			child = map[string]interface{}{}
			current[token] = child
		}
		current = child
	}
	current[tokens[len(tokens)-1]] = value
	return object
}

