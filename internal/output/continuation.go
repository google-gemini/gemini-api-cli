// advance reports whether another hop should be sent and, when it should,
// writes the resume values into the request.
func (r *continuationRun) advance() (bool, error) {
	if r.outcome.States[r.state] != "continue" {
		return false, nil
	}
	r.missing = nil
	for _, binding := range r.cfg.Bind {
		if !r.bindingEnabled(binding) {
			continue
		}
		if !binding.Optional && r.values[binding.To] == "" {
			r.missing = append(r.missing, binding.To)
		}
	}
	if len(r.missing) == 0 {
		r.fallback = cloneContinuationValues(r.values)
		r.fallbackValid = true
	}
	if len(r.missing) > 0 || !r.auto {
		return false, nil
	}
	if r.hops >= r.limit {
		r.limited = true
		return false, nil
	}
	for _, binding := range r.cfg.Bind {
		if !r.bindingEnabled(binding) {
			continue
		}
		value, ok := r.values[binding.To]
		if !ok {
			continue
		}
		if err := setContinuationBodyValue(r.request, binding.ToPath, value); err != nil {
			return false, r.wrap(WithCLIReason(fmt.Errorf("cannot set %s on the next request: %w", binding.To, err), ReasonCLIRuntime))
		}
	}
	return true, nil
}

func (r *continuationRun) send() (interface{}, error) {
	res, err := r.hop()
	if err != nil {
		if r.hops == 0 {
			return nil, err
		}
		return nil, r.wrap(err)
	}
	r.hops++
	return res, nil
}

