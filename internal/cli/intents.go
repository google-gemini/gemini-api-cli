		// commands are appended after the declared tree (InitDefaultHelpCmd
		// runs after initIntentCmds, and again inside Execute), so a declared
		// command that shares a builtin's name must keep its slot here.
		// Letting the later-added builtin claim the map entry would drop the
		// declared command from the re-added list entirely — a silently
		// swallowed command. Cobra dispatches to the earliest match, so
		// keeping the declared command first also keeps it runnable.
