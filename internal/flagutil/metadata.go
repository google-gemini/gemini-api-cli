// RegisterFlags registers Cobra flags from metadata, including union flags.
// Flags that already exist as inherited persistent flags (e.g., global security
// credentials) are skipped to prevent local flags from shadowing them.
func RegisterFlags(cmd *cobra.Command, meta []FlagMeta) {
	for order, m := range meta {
		// Skip if a flag with this name already exists — either inherited from
		// a parent command (persistent globals/security) or already registered
		// locally (e.g., operation security flags like username/password).
		if cmd.InheritedFlags().Lookup(m.FlagName) != nil || cmd.Flags().Lookup(m.FlagName) != nil {
			continue
		}

		switch m.Kind {
		case FlagKindUnion:
			if m.Union != nil {
				registerUnionFlags(cmd, m)
			}
		case FlagKindFile, FlagKindFileArray, FlagKindBytes:
			registerStringFlag(cmd, m)
		case FlagKindString, FlagKindEnum, FlagKindIntEnum, FlagKindJSON, FlagKindDateTime, FlagKindDate:
			registerStringFlag(cmd, m)
		case FlagKindBool:
			if m.Shorthand != "" {
				cmd.Flags().BoolP(m.FlagName, m.Shorthand, m.DefaultBool, m.Description)
			} else {
				cmd.Flags().Bool(m.FlagName, m.DefaultBool, m.Description)
			}
		case FlagKindInt64:
			if m.Shorthand != "" {
				cmd.Flags().Int64P(m.FlagName, m.Shorthand, m.DefaultInt, m.Description)
			} else {
				cmd.Flags().Int64(m.FlagName, m.DefaultInt, m.Description)
			}
		case FlagKindFloat64:
			if m.Shorthand != "" {
				cmd.Flags().Float64P(m.FlagName, m.Shorthand, m.DefaultFloat, m.Description)
			} else {
				cmd.Flags().Float64(m.FlagName, m.DefaultFloat, m.Description)
			}
		case FlagKindStringArray:
			if m.Shorthand != "" {
				cmd.Flags().StringArrayP(m.FlagName, m.Shorthand, nil, m.Description)
			} else {
				cmd.Flags().StringArray(m.FlagName, nil, m.Description)
			}
		}

		if cmd.Flags().Lookup(m.FlagName) != nil {
			_ = AnnotatePromptFlag(cmd, m.FlagName, PromptFlagSpec{
				Required:        promptMetaRequired(m),
				PromptOptional:  true,
				Kind:            promptKindName(m.Kind),
				Values:          m.EnumValues,
				Order:           order,
				EnvVar:          m.EnvVar,
				ConfigKey:       m.ConfigKey,
				DefaultResolves: m.HasDefault,
			})
		}
		if m.Group != "" {
			_ = cmd.Flags().SetAnnotation(m.FlagName, "speakeasy:group", []string{m.Group})
		}
	}
}

