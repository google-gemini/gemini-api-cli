func buildDateTimeField(cmd *cobra.Command, v reflect.Value, m FlagMeta) error {
	val, changed := GetStringFlag(cmd, m.FlagName)
	if err := validateRequiredPathParam(v, m, changed, val); err != nil {
		return err
	}
	if err := validateRequiredString(m, val); err != nil {
		return err
	}
	if shouldSkipUnchanged(m, changed) {
		return nil
	}
	if shouldSkipDefault(m, changed) {
		return nil
	}
	if val == "" {
		return nil
	}

	// Validate and parse RFC3339 format
	t, err := time.Parse(time.RFC3339Nano, val)
	if err != nil {
		t, err = time.Parse(time.RFC3339, val)
		if err != nil {
			return fmt.Errorf("invalid value for --%s: expected RFC3339 format (e.g., 2024-01-15T10:30:00Z), got %q", m.FlagName, val)
		}
	}

	// If the field type is time.Time, set the parsed value directly
	field, navErr := navigateToField(v, m.FieldPath)
	if navErr == nil {
		timeType := reflect.TypeOf(time.Time{})
		if field.Type() == timeType {
			field.Set(reflect.ValueOf(t))
			return nil
		}
		if field.Kind() == reflect.Ptr && field.Type().Elem() == timeType {
			field.Set(reflect.ValueOf(&t))
			return nil
		}
	}

	// For string-typed fields, store as-is
	return setFieldByPath(v, m.FieldPath, reflect.ValueOf(val))
}

func buildDateField(cmd *cobra.Command, v reflect.Value, m FlagMeta) error {
	val, changed := GetStringFlag(cmd, m.FlagName)
	if err := validateRequiredPathParam(v, m, changed, val); err != nil {
		return err
	}
	if err := validateRequiredString(m, val); err != nil {
		return err
	}
	if shouldSkipUnchanged(m, changed) {
		return nil
	}
	if shouldSkipDefault(m, changed) {
		return nil
	}
	if val == "" {
		return nil
	}

	// Validate date format (YYYY-MM-DD)
	if _, err := time.Parse("2006-01-02", val); err != nil {
		return fmt.Errorf("invalid value for --%s: expected date format (e.g., 2024-01-15), got %q", m.FlagName, val)
	}

	// If the field type is types.Date, parse and set directly
	field, navErr := navigateToField(v, m.FieldPath)
	if navErr == nil {
		dateType := reflect.TypeOf(types.Date{})
		if field.Type() == dateType {
			d, err := types.DateFromString(val)
			if err != nil {
				return fmt.Errorf("invalid value for --%s: %w", m.FlagName, err)
			}
			field.Set(reflect.ValueOf(d))
			return nil
		}
		if field.Kind() == reflect.Ptr && field.Type().Elem() == dateType {
			d, err := types.DateFromString(val)
			if err != nil {
				return fmt.Errorf("invalid value for --%s: %w", m.FlagName, err)
			}
			field.Set(reflect.ValueOf(&d))
			return nil
		}
	}

	// For string-typed fields, store as-is
	return setFieldByPath(v, m.FieldPath, reflect.ValueOf(val))
}

