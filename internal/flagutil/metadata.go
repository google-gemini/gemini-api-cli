func buildJSONField(cmd *cobra.Command, v reflect.Value, m FlagMeta) error {
	val, changed := GetStringFlag(cmd, m.FlagName)

	if m.Required && val == "" {
		return &MissingRequiredFlagError{FlagName: m.FlagName}
	}

	if m.Optional && !changed {
		return nil
	}

	if val == "" {
		return nil
	}

	// Navigate to the target field to get its type
	field, err := navigateToField(v, m.FieldPath)
	if err != nil {
		return fmt.Errorf("failed to navigate to field for --%s: %w", m.FlagName, err)
	}

	// Determine the concrete type (dereference pointer if needed)
	fieldType := field.Type()
	isPtr := fieldType.Kind() == reflect.Ptr
	if isPtr {
		fieldType = fieldType.Elem()
	}

	// JSON null: handle nullable fields where the CLI passes --field null.
	// For types implementing json.Unmarshaler (e.g., OptionalNullable), call the
	// custom unmarshaler directly — Go's json.Unmarshal sets pointers to nil for
	// "null" input, bypassing the custom UnmarshalJSON which distinguishes
	// "explicitly null" from "unset".
	if val == "null" {
		target := reflect.New(field.Type())
		if unmarshaler, ok := target.Interface().(json.Unmarshaler); ok {
			if err := unmarshaler.UnmarshalJSON([]byte("null")); err != nil {
				return fmt.Errorf("invalid value for --%s: %w", m.FlagName, err)
			}
			field.Set(target.Elem())
			return nil
		}
		// For non-Unmarshaler types: set pointer/interface fields to zero (nil)
		if isPtr || fieldType.Kind() == reflect.Interface {
			field.Set(reflect.Zero(field.Type()))
			return nil
		}
	}

	// For interface{} fields, use standard json.Unmarshal since the SDK's custom
	// unmarshaler doesn't handle unaddressable interface values.
	if fieldType.Kind() == reflect.Interface {
		var parsed interface{}
		if err := json.Unmarshal([]byte(val), &parsed); err != nil {
			// Not valid JSON — treat as raw string
			parsed = val
		}
		field.Set(reflect.ValueOf(parsed))
		return nil
	}

	// If the annotation specifies bigint:"string" or decimal:"string", the SDK's
	// unmarshalValue expects the value as a JSON string (e.g., "123"), not a bare
	// number. Wrap bare numbers in JSON quotes for user convenience.
	tag := reflect.StructTag(m.Annotations)
	if (tag.Get("bigint") == "string" || tag.Get("decimal") == "string") && val != "" && val[0] != '"' && val[0] != '[' && val[0] != '{' {
		val = `"` + val + `"`
	}

	// Unmarshal the JSON value into the field.
	// For pointer fields (e.g., *big.Int, *ModelType), we create a double-pointer
	// (**T) with a pre-initialized inner pointer (*T = &T{}). This ensures:
	// 1. The SDK's unmarshalValue can find a settable *T via v.Elem()
	// 2. dereferencePointers can walk through both levels without nil panics
	// 3. Model type fields are addressable for field-by-field unmarshaling
	if isPtr {
		holder := reflect.New(reflect.PtrTo(fieldType))
		holder.Elem().Set(reflect.New(fieldType))
		if err := utils.UnmarshalJsonFromString(val, holder.Interface(), m.Annotations); err != nil {
			return fmt.Errorf("invalid value for --%s: %w", m.FlagName, err)
		}
		field.Set(holder.Elem())
	} else {
		target := reflect.New(fieldType)
		if err := utils.UnmarshalJsonFromString(val, target.Interface(), m.Annotations); err != nil {
			return fmt.Errorf("invalid value for --%s: %w", m.FlagName, err)
		}
		field.Set(target.Elem())
	}

	return nil
}

func buildFileField(cmd *cobra.Command, v reflect.Value, m FlagMeta) error {
	path, changed := GetStringFlag(cmd, m.FlagName)

	if m.Required && (!changed || path == "") {
		return &MissingRequiredFlagError{FlagName: m.FlagName}
	}

	if !changed || path == "" {
		return nil // Optional and not provided
	}

	// Read file from disk
	content, err := os.ReadFile(path)
	if err != nil {
		return WithCLIValidation(fmt.Errorf("failed to read file for --%s: %w", m.FlagName, err))
	}
	fileName := filepath.Base(path)

	// Navigate to the file struct field
	field, navErr := navigateToField(v, m.FieldPath)
	if navErr != nil {
		return fmt.Errorf("failed to navigate to field for --%s: %w", m.FlagName, navErr)
	}

	// Determine concrete struct type (handle optional *FileType vs FileType)
	fieldType := field.Type()
	isPtr := fieldType.Kind() == reflect.Ptr
	if isPtr {
		fieldType = fieldType.Elem()
	}

	// Create file struct and set Content + FileName via reflection
	fileStruct := reflect.New(fieldType).Elem()
	if cf := fileStruct.FieldByName("Content"); cf.IsValid() && cf.CanSet() {
		cf.SetBytes(content)
	}
	if nf := fileStruct.FieldByName("FileName"); nf.IsValid() && nf.CanSet() {
		nf.SetString(fileName)
	}

	if isPtr {
		ptr := reflect.New(fieldType)
		ptr.Elem().Set(fileStruct)
		field.Set(ptr)
	} else {
		field.Set(fileStruct)
	}

	return nil
}

func buildFileArrayField(cmd *cobra.Command, v reflect.Value, m FlagMeta) error {
	val, changed := GetStringFlag(cmd, m.FlagName)

	if m.Required && (!changed || val == "") {
		return &MissingRequiredFlagError{FlagName: m.FlagName}
	}

	if !changed || val == "" {
		return nil
	}

	// Split comma-separated file paths, supporting optional ;fileName= overrides
	paths := strings.Split(val, ",")

	// Navigate to the slice field
	field, navErr := navigateToField(v, m.FieldPath)
	if navErr != nil {
		return fmt.Errorf("failed to navigate to field for --%s: %w", m.FlagName, navErr)
	}

	// Get the element type of the slice
	sliceType := field.Type()
	if sliceType.Kind() != reflect.Slice {
		return fmt.Errorf("field %s is not a slice type for --%s", m.FieldPath, m.FlagName)
	}
	elemType := sliceType.Elem()

	result := reflect.MakeSlice(sliceType, 0, len(paths))

	for _, entry := range paths {
		entry = strings.TrimSpace(entry)
		if entry == "" {
			continue
		}

		// Parse optional ;fileName=override syntax
		filePath := entry
		fileNameOverride := ""
		if idx := strings.Index(entry, ";fileName="); idx >= 0 {
			filePath = entry[:idx]
			fileNameOverride = entry[idx+len(";fileName="):]
		}

		content, err := os.ReadFile(filePath)
		if err != nil {
			return WithCLIValidation(fmt.Errorf("failed to read file %q for --%s: %w", filePath, m.FlagName, err))
		}

		fileName := filepath.Base(filePath)
		if fileNameOverride != "" {
			fileName = fileNameOverride
		}

		fileStruct := reflect.New(elemType).Elem()
		if cf := fileStruct.FieldByName("Content"); cf.IsValid() && cf.CanSet() {
			cf.SetBytes(content)
		}
		if nf := fileStruct.FieldByName("FileName"); nf.IsValid() && nf.CanSet() {
			nf.SetString(fileName)
		}

		result = reflect.Append(result, fileStruct)
	}

	field.Set(result)
	return nil
}

func buildBytesField(cmd *cobra.Command, v reflect.Value, m FlagMeta) error {
	val, changed := GetStringFlag(cmd, m.FlagName)
	if err := validateRequiredString(m, val); err != nil {
		return err
	}
	if shouldSkipUnchanged(m, changed) {
		return nil
	}
	if shouldSkipDefault(m, changed) {
		return nil
	}
	if val == "" {
		return nil
	}

	var data []byte
	switch {
	case strings.HasPrefix(val, "file:"):
		path := strings.TrimPrefix(val, "file:")
		var err error
		data, err = os.ReadFile(path)
		if err != nil {
			return WithCLIValidation(fmt.Errorf("failed to read file for --%s: %w", m.FlagName, err))
		}
	case strings.HasPrefix(val, "b64:"):
		raw := strings.TrimPrefix(val, "b64:")
		var err error
		data, err = base64.StdEncoding.DecodeString(raw)
		if err != nil {
			// Try raw (no padding), URL-safe, and raw URL-safe variants
			data, err = base64.RawStdEncoding.DecodeString(raw)
			if err != nil {
				data, err = base64.URLEncoding.DecodeString(raw)
				if err != nil {
					data, err = base64.RawURLEncoding.DecodeString(raw)
					if err != nil {
						return fmt.Errorf("invalid base64 for --%s: %w", m.FlagName, err)
					}
				}
			}
		}
	default:
		data = []byte(val)
	}

	return setFieldByPath(v, m.FieldPath, reflect.ValueOf(data))
}

// buildFieldOnValue dispatches to the appropriate per-kind builder.
// Used by BuildRequest for non-union fields and by buildUnionField for variant fields.
func buildFieldOnValue(cmd *cobra.Command, v reflect.Value, m FlagMeta) error {
	switch m.Kind {
	case FlagKindString:
		return buildStringField(cmd, v, m)
	case FlagKindBool:
		return buildBoolField(cmd, v, m)
	case FlagKindInt64:
		return buildInt64Field(cmd, v, m)
	case FlagKindFloat64:
		return buildFloat64Field(cmd, v, m)
	case FlagKindStringArray:
		return buildStringArrayField(cmd, v, m)
	case FlagKindDateTime:
		return buildDateTimeField(cmd, v, m)
	case FlagKindDate:
		return buildDateField(cmd, v, m)
	case FlagKindEnum:
		return buildEnumField(cmd, v, m)
	case FlagKindIntEnum:
		return buildIntEnumField(cmd, v, m)
	case FlagKindJSON:
		return buildJSONField(cmd, v, m)
	case FlagKindFile:
		return buildFileField(cmd, v, m)
	case FlagKindFileArray:
		return buildFileArrayField(cmd, v, m)
	case FlagKindBytes:
		return buildBytesField(cmd, v, m)
	}
	return nil
}

// registerUnionFlags registers all Cobra flags for a union field from its UnionMeta.
func registerUnionFlags(cmd *cobra.Command, m FlagMeta) {
	u := m.Union
	// Top-level JSON flag (skip if inherited persistent flag exists)
	if cmd.InheritedFlags().Lookup(m.FlagName) == nil {
		if m.Shorthand != "" {
			cmd.Flags().StringP(m.FlagName, m.Shorthand, "", u.TypeDescription)
		} else {
			cmd.Flags().String(m.FlagName, "", u.TypeDescription)
		}
	}

	// Per-variant flags (discriminated only)
	for _, v := range u.Variants {
		// Variant-level JSON flag (skip if inherited persistent flag exists)
		if cmd.InheritedFlags().Lookup(v.FlagName) == nil {
			cmd.Flags().String(v.FlagName, "", v.Description)
		}
		annotateUnionMember(cmd, v.FlagName, m.FlagName)

		// Expanded variant fields reuse RegisterFlags
		if v.CanExpand && len(v.Fields) > 0 {
			RegisterFlags(cmd, v.Fields)
			annotateUnionMembers(cmd, v.Fields, m.FlagName)
		}
	}
}

func annotateUnionMembers(cmd *cobra.Command, meta []FlagMeta, unionFlag string) {
	for _, m := range meta {
		annotateUnionMember(cmd, m.FlagName, unionFlag)
		if m.Union == nil {
			continue
		}
		for _, variant := range m.Union.Variants {
			annotateUnionMember(cmd, variant.FlagName, unionFlag)
			annotateUnionMembers(cmd, variant.Fields, unionFlag)
		}
	}
}

func annotateUnionMember(cmd *cobra.Command, name, unionFlag string) {
	f := cmd.Flags().Lookup(name)
	if f == nil {
		return
	}
	if f.Annotations == nil {
		f.Annotations = map[string][]string{}
	}
	f.Annotations[AnnotationUnionMember] = []string{unionFlag}
}

// buildUnionField handles the complete union parsing flow:
// variant conflict detection, 3-priority parsing, and field assignment.
func buildUnionField(cmd *cobra.Command, root reflect.Value, m FlagMeta) error {
	u := m.Union

	// Navigate to the union field on the request struct
	unionField, err := navigateToField(root, m.FieldPath)
	if err != nil {
		return fmt.Errorf("failed to navigate to union field for --%s: %w", m.FlagName, err)
	}

	// Determine concrete type (handle optional *UnionType vs UnionType)
	unionType := unionField.Type()
	isPtr := unionType.Kind() == reflect.Ptr
	if isPtr {
		unionType = unionType.Elem()
	}

	// Check if any union-related flags were set
	anySet := FlagChanged(cmd, m.FlagName)
	if !anySet && u.Discriminated {
		for _, v := range u.Variants {
			if HasAnyFlagWithPrefix(cmd, v.FlagName) {
				anySet = true
				break
			}
		}
	}

	if !anySet {
		if u.Optional {
			return nil // Leave field as nil
		}
		if !u.Discriminated {
			return &MissingRequiredFlagError{FlagName: m.FlagName}
		}
		// Discriminated required with nothing set: leave as zero (matches current behavior)
		return nil
	}

	// Discriminated union: check variant conflicts
	if u.Discriminated {
		var variantsSet []string
		for _, v := range u.Variants {
			if HasAnyFlagWithPrefix(cmd, v.FlagName) {
				variantsSet = append(variantsSet, v.DiscriminatorValue)
			}
		}
		if len(variantsSet) > 1 {
			names := make([]string, len(u.Variants))
			for i, v := range u.Variants {
				names[i] = v.DiscriminatorValue
			}
			return fmt.Errorf("multiple union variants provided for --%s; choose one of: %s",
				m.FlagName, strings.Join(names, ", "))
		}
	}

	// Priority 1: Top-level JSON flag
	if FlagChanged(cmd, m.FlagName) {
		jsonStr, _ := GetStringFlag(cmd, m.FlagName)
		target := reflect.New(unionType)
		if err := utils.UnmarshalJsonFromString(string(applyUnionDefaults([]byte(jsonStr), u)), target.Interface(), ""); err != nil {
			return fmt.Errorf("invalid value for --%s: %w", m.FlagName, err)
		}
		if err := enforceStrictOrWarn(cmd, verifyBodyKeys("--"+m.FlagName, []byte(jsonStr), target, u)); err != nil {
			return err
		}
		setUnionFieldValue(unionField, target, isPtr)
		return nil
	}

	// Priority 2 & 3: Per-variant flags (discriminated only)
	for _, v := range u.Variants {
		if !HasAnyFlagWithPrefix(cmd, v.FlagName) {
			continue
		}

		// Find the variant's Go type via reflection on the union struct
		variantStructField, ok := unionType.FieldByName(v.FieldName)
		if !ok {
			return fmt.Errorf("variant field %q not found on union type %s", v.FieldName, unionType)
		}
		// Variant fields are always *VariantType pointers
		variantType := variantStructField.Type.Elem()

		// Priority 2: Variant-level JSON flag
		if FlagChanged(cmd, v.FlagName) {
			jsonStr, _ := GetStringFlag(cmd, v.FlagName)
			variantPtr := reflect.New(variantType)
			if err := utils.UnmarshalJsonFromString(jsonStr, variantPtr.Interface(), ""); err != nil {
				return fmt.Errorf("invalid value for --%s: %w", v.FlagName, err)
			}
			injectDiscriminator(variantPtr.Elem(), u.DiscriminatorKey, v.DiscriminatorValue)
			unionVal := assembleUnionValue(unionType, v.FieldName, variantPtr)
			setUnionFieldValue(unionField, unionVal, isPtr)
			return nil
		}

		// Priority 3: Expanded variant fields
		if v.CanExpand {
			variantVal := reflect.New(variantType).Elem()
			injectDiscriminator(variantVal, u.DiscriminatorKey, v.DiscriminatorValue)

			// Build variant fields using the same per-kind builders
			for _, fm := range v.Fields {
				if err := buildFieldOnValue(cmd, variantVal, fm); err != nil {
					return err
				}
			}

			variantPtr := reflect.New(variantType)
			variantPtr.Elem().Set(variantVal)
			unionVal := assembleUnionValue(unionType, v.FieldName, variantPtr)
			setUnionFieldValue(unionField, unionVal, isPtr)
			return nil
		}
	}

	return nil
}

// setUnionFieldValue sets a union field on the request struct.
// Handles both value (Shape) and pointer (*Shape) field types.
func setUnionFieldValue(field reflect.Value, val reflect.Value, isPtr bool) {
	if isPtr {
		// field is *UnionType, val is *UnionType from reflect.New
		field.Set(val)
	} else if val.Kind() == reflect.Ptr {
		// field is UnionType, val is *UnionType → dereference
		field.Set(val.Elem())
	} else {
		field.Set(val)
	}
}

// injectDiscriminator sets the discriminator field on a variant struct value.
func injectDiscriminator(v reflect.Value, key string, value string) {
	if key == "" {
		return
	}
	f := v.FieldByName(key)
	if f.IsValid() && f.CanSet() {
		f.Set(reflect.ValueOf(value).Convert(f.Type()))
	}
}

// assembleUnionValue creates a new union struct with the given variant pointer set.
func assembleUnionValue(unionType reflect.Type, variantFieldName string, variantPtr reflect.Value) reflect.Value {
	unionVal := reflect.New(unionType)
	unionElem := unionVal.Elem()
	vf := unionElem.FieldByName(variantFieldName)
	if vf.IsValid() && vf.CanSet() {
		vf.Set(variantPtr)
	}
	return unionVal
}
