// HTTPClient is the interface that SDK clients implement.
type HTTPClient interface {
	Do(req *http.Request) (*http.Response, error)
}

// Do executes the request, logging diagnostics before and after.
func (c *DebugClient) Do(req *http.Request) (*http.Response, error) {
	// Log request
	fmt.Fprintf(c.Stderr, "[DEBUG] Request: %s %s\n", req.Method, redactURL(req.URL.String()))
	fmt.Fprintf(c.Stderr, "[DEBUG] Request Headers:\n%s", formatHeaders(redactHeaders(req.Header)))
	if req.Body != nil {
		bodyData, restored, readErr := readAndRestoreBody(req.Body)
		req.Body = restored
		if readErr != nil {
			fmt.Fprintf(c.Stderr, "[DEBUG] Request Body Read Error: %v\n", readErr)
		} else {
			body := previewBody(bodyData, req.Header.Get("Content-Type"))
			fmt.Fprintf(c.Stderr, "[DEBUG] Request Body:\n  %s\n", formatBodyPreview(body, maxBodyPreview))
		}
	}

	// Execute
	resp, err := c.Inner.Do(req)
	if err != nil {
		fmt.Fprintf(c.Stderr, "[DEBUG] Transport Error: %v\n", err)
		return nil, err
	}

	// Log response
	fmt.Fprintf(c.Stderr, "[DEBUG] Response: %d %s\n", resp.StatusCode, resp.Status)
	fmt.Fprintf(c.Stderr, "[DEBUG] Response Headers:\n%s", formatHeaders(redactHeaders(resp.Header)))
	if resp.Body != nil {
		if isStreamingResponse(resp) {
			// Reading a streaming body here buffers every event until the server closes the stream.
			fmt.Fprintf(c.Stderr, "[DEBUG] Response Body: <streaming %s; not captured>\n", resp.Header.Get("Content-Type"))
		} else {
			bodyData, restored, readErr := readAndRestoreBody(resp.Body)
			resp.Body = restored
			if readErr != nil {
				fmt.Fprintf(c.Stderr, "[DEBUG] Response Body Read Error: %v\n", readErr)
			} else if len(bodyData) > 0 {
				body := previewBody(bodyData, resp.Header.Get("Content-Type"))
				fmt.Fprintf(c.Stderr, "[DEBUG] Response Body:\n  %s\n", formatBodyPreview(body, maxBodyPreview))
			}
		}
	}

	return resp, nil
}

func isStreamingResponse(resp *http.Response) bool {
	mediaType := strings.ToLower(strings.TrimSpace(strings.SplitN(resp.Header.Get("Content-Type"), ";", 2)[0]))
	if strings.HasPrefix(mediaType, "text/event-stream") {
		return true
	}
	for _, suffix := range []string{"jsonl", "x-ndjson", "json-seq"} {
		if strings.HasSuffix(mediaType, "/"+suffix) || strings.HasSuffix(mediaType, "+"+suffix) {
			return true
		}
	}
	return false
}

// DryRunClient intercepts HTTP requests and returns a synthetic response
// without making any network calls.
type DryRunClient struct {
	Stderr io.Writer
	Stdout io.Writer
	JSON   bool
	Cmd    *cobra.Command
}

type dryRunBody struct{ length int64 }

// NewDryRunBody returns an empty body that previews as <bytes:length> under --dry-run.
func NewDryRunBody(length int64) io.ReadCloser { return &dryRunBody{length: length} }

func (b *dryRunBody) Read([]byte) (int, error) { return 0, io.EOF }
func (b *dryRunBody) Close() error             { return nil }

type dryRunPreview struct {
	DryRun  bool                 `json:"dry_run"`
	Request dryRunPreviewRequest `json:"request"`
}

type dryRunPreviewRequest struct {
	Method  string      `json:"method"`
	URL     string      `json:"url"`
	Headers http.Header `json:"headers"`
	Body    interface{} `json:"body"`
}

func (c *DryRunClient) Do(req *http.Request) (*http.Response, error) {
	flagutil.MarkDryRunRequest(c.Cmd)
	var body interface{}
	var bodyData []byte
	if placeholder, ok := req.Body.(*dryRunBody); ok {
		body = fmt.Sprintf("<bytes:%d>", placeholder.length)
	} else if req.Body != nil {
		var restored io.ReadCloser
		var err error
		bodyData, restored, err = readAndRestoreBody(req.Body)
		req.Body = restored
		if err != nil {
			return nil, fmt.Errorf("read request body for dry-run preview: %w", err)
		}
		body = previewBody(bodyData, req.Header.Get("Content-Type"))
	}
	requestURL := redactURL(req.URL.String())
	headers := redactHeaders(req.Header)
	if c.JSON {
		out := c.Stdout
		if out == nil {
			out = io.Discard
		}
		enc := json.NewEncoder(out)
		enc.SetEscapeHTML(false)
		if err := enc.Encode(dryRunPreview{
			DryRun: true,
			Request: dryRunPreviewRequest{
				Method: req.Method, URL: requestURL, Headers: headers, Body: body,
			},
		}); err != nil {
			return nil, fmt.Errorf("write dry-run preview: %w", err)
		}
	} else {
		stderr := c.Stderr
		if stderr == nil {
			stderr = io.Discard
		}
		fmt.Fprintf(stderr, "[DRY-RUN] Would send: %s %s\n", req.Method, requestURL)
		fmt.Fprintf(stderr, "[DRY-RUN] Headers:\n%s", formatHeaders(headers))
		if req.Body != nil {
			fmt.Fprintf(stderr, "[DRY-RUN] Body:\n  %s\n", formatBodyPreview(body, 0))
		}
		fmt.Fprintf(stderr, "[DRY-RUN] Network call skipped.\n")
	}

	contentType, syntheticBody := dryRunResponseShape(req.Header.Get("Accept"))
	if isTokenExchange(req, bodyData) {
		contentType = "application/json"
		syntheticBody = []byte(`{"access_token":"[DRY-RUN]","token_type":"Bearer","expires_in":3600}`)
	}
	return &http.Response{
		StatusCode: http.StatusOK,
		Status:     "200 OK",
		Header:     http.Header{"Content-Type": []string{contentType}},
		Body:       io.NopCloser(bytes.NewReader(syntheticBody)),
		Request:    req,
	}, nil
}

func isTokenExchange(req *http.Request, body []byte) bool {
	if req == nil || req.URL == nil {
		return false
	}
	if req.Method == http.MethodPost && strings.HasSuffix(strings.TrimSuffix(strings.ToLower(req.URL.Path), "/"), "/token") {
		return true
	}
	mediaType, _, _ := mime.ParseMediaType(req.Header.Get("Content-Type"))
	switch {
	case mediaType == "application/x-www-form-urlencoded":
		values, err := url.ParseQuery(string(body))
		return err == nil && values.Has("grant_type")
	case isJSONMediaType(mediaType):
		dec := json.NewDecoder(bytes.NewReader(body))
		dec.UseNumber()
		var value interface{}
		return dec.Decode(&value) == nil && containsJSONKey(value, "granttype")
	default:
		return false
	}
}

func containsJSONKey(value interface{}, normalizedKey string) bool {
	switch current := value.(type) {
	case map[string]interface{}:
		for key, child := range current {
			if normalizeSensitiveKey(key) == normalizedKey || containsJSONKey(child, normalizedKey) {
				return true
			}
		}
	case []interface{}:
		for _, child := range current {
			if containsJSONKey(child, normalizedKey) {
				return true
			}
		}
	}
	return false
}

func isJSONMediaType(mediaType string) bool {
	mediaType = strings.ToLower(mediaType)
	return mediaType == "application/json" || strings.HasSuffix(mediaType, "+json")
}

// Generated response dispatch may match the complete Content-Type value, parameters included.
func dryRunResponseShape(accept string) (string, []byte) {
	first := ""
	for _, part := range strings.Split(accept, ",") {
		segments := strings.Split(part, ";")
		baseType := strings.TrimSpace(segments[0])
		if baseType == "" {
			continue
		}

		params := make([]string, 0, len(segments)-1)
		for _, segment := range segments[1:] {
			param := strings.TrimSpace(segment)
			if param == "" {
				continue
			}
			name := strings.TrimSpace(strings.SplitN(param, "=", 2)[0])
			if strings.EqualFold(name, "q") {
				continue
			}
			params = append(params, param)
		}

		acceptedType := baseType
		if len(params) > 0 {
			acceptedType += "; " + strings.Join(params, "; ")
		}
		if baseType == "*/*" {
			return "application/json", []byte("{}")
		}
		if isJSONMediaType(baseType) {
			return acceptedType, []byte("{}")
		}
		if first == "" {
			first = acceptedType
		}
	}
	if first == "" {
		return "application/json", []byte("{}")
	}
	return first, nil
}

// WrapClientForDiagnostics wraps an HTTP client based on diagnostics mode.
// Returns the original client if no diagnostics flags are set.
func WrapClientForDiagnostics(cmd *cobra.Command, inner HTTPClient) HTTPClient {
	stderr := cmd.ErrOrStderr()
	if IsDryRun(cmd) {
		return &DryRunClient{Stderr: stderr, Stdout: cmd.OutOrStdout(), JSON: IsJSONDryRun(cmd), Cmd: cmd}
	}
	if IsDebug(cmd) {
		return &DebugClient{Inner: inner, Stderr: stderr}
	}
	return inner
}
