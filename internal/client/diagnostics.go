// IsDryRun returns true when --dry-run is set on the command.
func IsDryRun(cmd *cobra.Command) bool {
	v, _ := flagutil.GetBoolFlag(cmd, "dry-run")
	return v
}

func IsJSONDryRun(cmd *cobra.Command) bool {
	if !IsDryRun(cmd) {
		return false
	}
	format := flagutil.ResolveOutputFormat(cmd, config.GetString("output-format"), false)
	return format == "json" || flagutil.FlagChanged(cmd, "jq")
}

// IsDebug returns true when --debug is set and --dry-run is not.
// When both flags are set, dry-run takes precedence.
func IsDebug(cmd *cobra.Command) bool {
	if IsDryRun(cmd) {
		return false
	}
	v, _ := flagutil.GetBoolFlag(cmd, "debug")
	return v
}

