func wholeBodySupplied(cmd *cobra.Command) (bool, error) {
	bodyFlag := cmd.Annotations[flagutil.AnnotationWholeBodyFlag]
	if bodyFlag == "" {
		return false, nil
	}
	f := cmd.Flags().Lookup(bodyFlag)
	if f == nil {
		return false, nil
	}
	if f.Changed {
		return true, nil
	}
	data, err := flagutil.ReadStdinBody(cmd, bodyFlag)
	if err != nil {
		return false, err
	}
	if len(bytes.TrimSpace(data)) == 0 {
		return false, nil
	}
	value := string(data)
	// "@@" is ResolveBodyFlagValue's escape for a literal leading "@".
	if strings.HasPrefix(value, "@") {
		value = "@" + value
	}
	if err := cmd.Flags().Set(bodyFlag, value); err != nil {
		return false, err
	}
	return true, nil
}

