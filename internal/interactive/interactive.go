func documentationRequested(cmd *cobra.Command) bool {
	requested := false
	cmd.Flags().VisitAll(func(f *pflag.Flag) {
		if requested || !annotationTrue(f, flagutil.AnnotationDocSurface) || !f.Changed {
			return
		}
		if f.Value.Type() == "bool" {
			value, err := strconv.ParseBool(f.Value.String())
			requested = err == nil && value
			return
		}
		requested = true
	})
	return requested
}

func hasMissingDeclaredRequiredArg(cmd *cobra.Command, args []string, spec []ArgSpec) bool {
	for i, arg := range spec {
		if arg.Required && !argResolved(cmd, args, i, arg) {
			return true
		}
	}
	return false
}

func argResolved(cmd *cobra.Command, args []string, index int, arg ArgSpec) bool {
	if index < len(args) {
		return true
	}
	for _, name := range arg.SatisfiedBy {
		if alternativeFlagSet(cmd, name) {
			return true
		}
	}
	return false
}

func alternativeFlagSet(cmd *cobra.Command, name string) bool {
	f := cmd.Flags().Lookup(name)
	if f == nil || !f.Changed {
		return false
	}
	switch f.Value.Type() {
	case "bool":
		v, err := strconv.ParseBool(f.Value.String())
		return err == nil && v
	case "stringArray", "stringSlice":
		return strings.TrimSpace(f.Value.String()) != "[]"
	default:
		return strings.TrimSpace(f.Value.String()) != ""
	}
}

func promptPlan(cmd *cobra.Command, args []string, spec []ArgSpec) ([]PromptField, bool, error) {
	var requiredArgs, optionalArgs, requiredFlags, directFlags, optionalFlags []PromptField
	missing := false
	for i, arg := range spec {
		if argResolved(cmd, args, i, arg) {
			continue
		}
		field := PromptField{
			ID:         "arg:" + arg.Name,
			Name:       displayName(arg.Name, "", arg.Required),
			Summary:    arg.Summary,
			Kind:       "string",
			Required:   arg.Required,
			Repeatable: arg.Variadic,
			target:     promptTargetArg,
			argIndex:   i,
		}
		if arg.Required {
			missing = true
			requiredArgs = append(requiredArgs, field)
		} else {
			optionalArgs = append(optionalArgs, field)
		}
	}

	cmd.Flags().VisitAll(func(f *pflag.Flag) {
		if len(f.Annotations[flagutil.AnnotationUnionMember]) > 0 {
			return
		}
		required := annotationTrue(f, flagutil.AnnotationRequired) || annotationTrue(f, cobra.BashCompOneRequiredFlag)
		optional := annotationTrue(f, flagutil.AnnotationPrompt)
		direct := annotationTrue(f, flagutil.AnnotationPromptDirect)
		if (!required && !optional && !direct) || flagResolved(cmd, f) {
			return
		}
		kind, repeatable := promptKind(f)
		options := append([]string(nil), f.Annotations[flagutil.AnnotationPromptValues]...)
		if kind == "enum" && len(options) == 0 {
			kind = "string"
		}
		summary := flagSummary(f)
		if direct {
			summary += " · optional; leave empty for the default"
		}
		field := PromptField{
			ID:         "flag:" + f.Name,
			Name:       displayName(f.Name, firstAnnotation(f, flagutil.AnnotationPromptLabel), required),
			Summary:    summary,
			Kind:       kind,
			Required:   required,
			Direct:     direct,
			Repeatable: repeatable,
			Options:    options,
			target:     promptTargetFlag,
			flagName:   f.Name,
		}
		if required {
			missing = true
			requiredFlags = append(requiredFlags, field)
		} else if direct {
			directFlags = append(directFlags, field)
		} else {
			optionalFlags = append(optionalFlags, field)
		}
	})

	sortPromptFlags(requiredFlags, cmd)
	sortPromptFlags(directFlags, cmd)
	sortPromptFlags(optionalFlags, cmd)
	if !missing {
		return nil, false, nil
	}
	fields := append(requiredArgs, requiredFlags...)
	fields = append(fields, optionalArgs...)
	fields = append(fields, directFlags...)
	fields = append(fields, optionalFlags...)
	return fields, true, nil
}

func firstAnnotation(f *pflag.Flag, key string) string {
	if f == nil || len(f.Annotations[key]) == 0 {
		return ""
	}
	return f.Annotations[key][0]
}

func sortPromptFlags(fields []PromptField, cmd *cobra.Command) {
	sort.SliceStable(fields, func(i, j int) bool {
		left := promptOrder(cmd.Flags().Lookup(fields[i].flagName))
		right := promptOrder(cmd.Flags().Lookup(fields[j].flagName))
		if left == right {
			return fields[i].flagName < fields[j].flagName
		}
		return left < right
	})
}

func promptOrder(f *pflag.Flag) int {
	if f == nil || len(f.Annotations[flagutil.AnnotationPromptOrder]) == 0 {
		return int(^uint(0) >> 1)
	}
	v, err := strconv.Atoi(f.Annotations[flagutil.AnnotationPromptOrder][0])
	if err != nil {
		return int(^uint(0) >> 1)
	}
	return v
}

func annotationTrue(f *pflag.Flag, key string) bool {
	values := f.Annotations[key]
	return len(values) > 0 && values[0] == "true"
}

func flagResolved(cmd *cobra.Command, f *pflag.Flag) bool {
	if f == nil {
		return true
	}
	if f.Changed || annotationTrue(f, flagutil.AnnotationDefaultResolves) {
		return true
	}
	for _, source := range f.Annotations[flagutil.AnnotationBodyField] {
		if body := cmd.Flags().Lookup(source); body != nil && body.Changed {
			return true
		}
	}
	if values := f.Annotations[flagutil.AnnotationEnv]; len(values) > 0 {
		if _, ok := os.LookupEnv(values[0]); ok {
			return true
		}
	}
	if values := f.Annotations[flagutil.AnnotationConfig]; len(values) > 0 {
		if config.GetConfigValue(values[0]) != "" {
			return true
		}
	}
	return false
}

func promptKind(f *pflag.Flag) (string, bool) {
	if values := f.Annotations[flagutil.AnnotationPromptKind]; len(values) > 0 && values[0] != "" {
		kind := values[0]
		return kind, kind == "string-array"
	}
	switch f.Value.Type() {
	case "bool":
		return "bool", false
	case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64":
		return "int64", false
	case "float32", "float64":
		return "float64", false
	case "duration":
		return "duration", false
	case "stringArray", "stringSlice":
		return "string-array", true
	default:
		return "string", false
	}
}

func flagSummary(f *pflag.Flag) string {
	if f.Usage == "" {
		return "--" + f.Name
	}
	return f.Usage + " · --" + f.Name
}

func displayName(name, label string, required bool) string {
	if strings.TrimSpace(label) != "" {
		name = label
		if required {
			name += " (required)"
		}
		return name
	}
	if idx := strings.LastIndex(name, "."); idx >= 0 {
		name = name[idx+1:]
	}
	parts := strings.Split(name, "-")
	for i, part := range parts {
		if part != "" {
			parts[i] = strings.ToUpper(part[:1]) + part[1:]
		}
	}
	name = strings.Join(parts, " ")
	if required {
		name += " (required)"
	}
	return name
}

func applyAnswers(cmd *cobra.Command, args []string, fields []PromptField, answers []PromptAnswer) ([]string, error) {
	if len(answers) != len(fields) {
		return nil, fmt.Errorf("interactive prompt returned %d answer(s) for %d field(s)", len(answers), len(fields))
	}
	effective := append([]string(nil), args...)
	for i, field := range fields {
		answer := answers[i]
		answerHasValue := false
		for _, value := range answer.Values {
			if strings.TrimSpace(value) != "" {
				answerHasValue = true
				break
			}
		}
		if !answer.Set || !answerHasValue {
			if field.Required {
				return nil, fmt.Errorf("interactive prompt left required input %q unset", field.ID)
			}
			continue
		}
		if field.target == promptTargetArg {
			for _, value := range answer.Values {
				if value != "" {
					effective = append(effective, value)
				}
			}
			continue
		}
		values := answer.Values
		if !field.Repeatable && len(values) > 1 {
			values = values[:1]
		}
		for _, value := range values {
			if err := cmd.Flags().Set(field.flagName, value); err != nil {
				return nil, fmt.Errorf("setting flag %q: %w", field.flagName, err)
			}
		}
	}
	return effective, nil
}

// formWidth returns the terminal width for sizing huh forms, with a sensible default.
func formWidth() int {
	width, _, err := term.GetSize(int(os.Stdout.Fd()))
	if err != nil || width <= 0 {
		width = 80
	}
	return width
}

