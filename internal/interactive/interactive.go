func Declare(cmd *cobra.Command, spec CommandSpec) error {
	if cmd == nil {
		return fmt.Errorf("declare interactive arguments: nil command")
	}
	for i, arg := range spec.Args {
		if strings.TrimSpace(arg.Name) == "" {
			return fmt.Errorf("declare interactive arguments: argument %d has no name", i+1)
		}
		if arg.Variadic && i != len(spec.Args)-1 {
			return fmt.Errorf("declare interactive arguments: variadic argument %q must be last", arg.Name)
		}
	}
	raw, err := json.Marshal(promptArgsWire{Version: 1, Args: spec.Args})
	if err != nil {
		return fmt.Errorf("declare interactive arguments: %w", err)
	}
	if cmd.Annotations == nil {
		cmd.Annotations = map[string]string{}
	}
	cmd.Annotations[PromptArgsAnnotation] = string(raw)
	if cmd.Annotations["speakeasy_args_help"] == "" && !strings.Contains(cmd.Long, "Arguments:\n") {
		parts := make([]string, 0, len(spec.Args))
		for _, arg := range spec.Args {
			name := arg.Name
			if arg.Required {
				name = "<" + name + ">"
			} else {
				name = "[" + name + "]"
			}
			if arg.Variadic {
				name += "..."
			}
			parts = append(parts, name)
		}
		cmd.Annotations["speakeasy_args_help"] = strings.Join(parts, " ")
	}
	return nil
}

