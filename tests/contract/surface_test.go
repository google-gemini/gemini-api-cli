// The CLI surface golden records every command, flag, shorthand, flag type
// and default of the gemini-api command tree. Scripts and agents depend on
// all of them, and the generator can change them as a side effect of an
// unrelated spec change: adding a flag that starts with the same letter as
// an existing one silently drops the existing flag's shorthand. Pinning the
// tree makes every such change show up as a reviewed diff.

const surfaceGoldenRel = "testdata/cli_surface.golden"

var enumOptionsPattern = regexp.MustCompile(`\(options: ([^)]*)\)`)

var (
	updateSurface = flag.Bool("update_cli_surface", false, "rewrite "+surfaceGoldenRel+" from the current command tree (additive changes only unless -allow_breaking is set)")
	allowBreaking = flag.Bool("allow_breaking", false, "allow -update_cli_surface to write removed or changed command/flag entries")
)

const surfaceUpdateHelp = `To accept an additive change, regenerate the golden and include it in your change:
  go test ./tests/contract -run TestCLISurfaceGolden -update_cli_surface
(or run this package's test target with -test.run=TestCLISurfaceGolden -update_cli_surface).
Removed or changed lines break existing scripts: pass -allow_breaking only when
the breaking change is intentional, and call it out in the change description.`

// surfaceLine is one golden entry: a stable key (a command path, or a
// command path and a flag name) and the attributes recorded for it.
type surfaceLine struct {
	key, attrs string
}

func (l surfaceLine) String() string {
	if l.attrs == "" {
		return l.key
	}
	return l.key + "  " + l.attrs
}

// cliSurface returns the golden lines for root and all its descendants,
// sorted by key. Inherited flags are recorded once, on the command that
// declares them.
func cliSurface(root *cobra.Command) []surfaceLine {
	var lines []surfaceLine
	var walk func(*cobra.Command)
	walk = func(cmd *cobra.Command) {
		path := cmd.CommandPath()
		var attrs []string
		if cmd.Hidden {
			attrs = append(attrs, "hidden")
		}
		if cmd.Deprecated != "" {
			attrs = append(attrs, "deprecated")
		}
		if len(cmd.Aliases) > 0 {
			aliases := append([]string(nil), cmd.Aliases...)
			sort.Strings(aliases)
			attrs = append(attrs, "aliases="+strings.Join(aliases, ","))
		}
		lines = append(lines, surfaceLine{"cmd " + path, strings.Join(attrs, " ")})

		record := func(f *pflag.Flag, persistent bool) {
			short := "-"
			if f.Shorthand != "" {
				short = "-" + f.Shorthand
			}
			fa := []string{"short=" + short, "type=" + f.Value.Type(), fmt.Sprintf("default=%q", f.DefValue)}
			// Enum flags list their accepted values in the usage text.
			if m := enumOptionsPattern.FindStringSubmatch(f.Usage); m != nil {
				opts := strings.Split(m[1], ",")
				for i := range opts {
					opts[i] = strings.TrimSpace(opts[i])
				}
				sort.Strings(opts)
				fa = append(fa, "options="+strings.Join(opts, ","))
			}
			if persistent {
				fa = append(fa, "persistent")
			}
			if f.Hidden {
				fa = append(fa, "hidden")
			}
			if f.Deprecated != "" {
				fa = append(fa, "deprecated")
			}
			if f.ShorthandDeprecated != "" {
				fa = append(fa, "shorthand-deprecated")
			}
			if req := f.Annotations[cobra.BashCompOneRequiredFlag]; len(req) > 0 && req[0] == "true" {
				fa = append(fa, "required")
			}
			lines = append(lines, surfaceLine{"flag " + path + " --" + f.Name, strings.Join(fa, " ")})
		}
		cmd.PersistentFlags().VisitAll(func(f *pflag.Flag) { record(f, true) })
		cmd.LocalNonPersistentFlags().VisitAll(func(f *pflag.Flag) { record(f, false) })

		for _, sub := range cmd.Commands() {
			walk(sub)
		}
	}
	walk(root)
	sort.Slice(lines, func(i, j int) bool { return lines[i].key < lines[j].key })
	return lines
}

func formatSurface(lines []surfaceLine) string {
	var b strings.Builder
	b.WriteString("# gemini-api command surface: commands, flags, shorthands, types and defaults.\n")
	b.WriteString("# Generated by TestCLISurfaceGolden (tests/contract/surface_test.go); do not edit by hand.\n")
	for _, l := range lines {
		b.WriteString(l.String())
		b.WriteByte('\n')
	}
	return b.String()
}

func parseSurface(text string) map[string]string {
	entries := make(map[string]string)
	for _, raw := range strings.Split(text, "\n") {
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, attrs, _ := strings.Cut(line, "  ")
		entries[key] = attrs
	}
	return entries
}

// surfaceDiff classifies the difference between the golden (want) and the
// current tree (got). Removed and changed entries are breaking for anyone
// who scripts the CLI; added entries are not.
type surfaceDiff struct {
	removed, changed, added []string
}

func (d surfaceDiff) empty() bool {
	return len(d.removed) == 0 && len(d.changed) == 0 && len(d.added) == 0
}

func (d surfaceDiff) breaking() bool { return len(d.removed) > 0 || len(d.changed) > 0 }

func shouldRefuseSurfaceUpdate(d surfaceDiff, allowBreaking bool) bool {
	return d.breaking() && !allowBreaking
}

func (d surfaceDiff) String() string {
	var b strings.Builder
	section := func(title string, items []string) {
		if len(items) == 0 {
			return
		}
		fmt.Fprintf(&b, "%s (%d):\n", title, len(items))
		for _, item := range items {
			fmt.Fprintf(&b, "  %s\n", item)
		}
	}
	section("BREAKING: removed", d.removed)
	section("BREAKING: changed", d.changed)
	section("Added", d.added)
	return b.String()
}

func diffSurface(want, got map[string]string) surfaceDiff {
	var d surfaceDiff
	for key, wantAttrs := range want {
		gotAttrs, ok := got[key]
		switch {
		case !ok:
			d.removed = append(d.removed, key+"  "+wantAttrs)
		case gotAttrs != wantAttrs:
			d.changed = append(d.changed, fmt.Sprintf("%s\n      was: %s\n      now: %s", key, wantAttrs, gotAttrs))
		}
	}
	for key, gotAttrs := range got {
		if _, ok := want[key]; !ok {
			d.added = append(d.added, key+"  "+gotAttrs)
		}
	}
	sort.Strings(d.removed)
	sort.Strings(d.changed)
	sort.Strings(d.added)
	return d
}

// surfaceGoldenPath returns where to read the golden from and, for
// -update_cli_surface, where to write it. A test runner that executes the test
// from a runfiles tree sets BUILD_WORKSPACE_DIRECTORY for "run" invocations;
// the golden is then written to the matching path in the source tree instead
// of the read-only runfiles copy.
func surfaceGoldenPath(t *testing.T, forWrite bool) string {
	t.Helper()
	root, err := repoRoot()
	if err != nil {
		t.Fatal(err)
	}
	inRepo := filepath.Join(root, "tests", "contract", surfaceGoldenRel)
	ws := os.Getenv("BUILD_WORKSPACE_DIRECTORY")
	if !forWrite || ws == "" {
		return inRepo
	}
	for _, runfiles := range []string{
		filepath.Join(os.Getenv("TEST_SRCDIR"), os.Getenv("TEST_WORKSPACE")),
		filepath.Join(os.Getenv("RUNFILES_DIR"), os.Getenv("TEST_WORKSPACE")),
	} {
		if rel, err := filepath.Rel(runfiles, inRepo); err == nil && !strings.HasPrefix(rel, "..") {
			return filepath.Join(ws, rel)
		}
	}
	t.Fatalf("cannot map %s into the source tree at %s", inRepo, ws)
	return ""
}

// isolateCLIEnv clears the GEMINI_* environment and points HOME at an empty
// directory so flag defaults cannot pick up the developer's configuration.
func isolateCLIEnv(t *testing.T) {
	t.Helper()
	for _, kv := range os.Environ() {
		name, _, _ := strings.Cut(kv, "=")
		if strings.HasPrefix(name, "GEMINI_") || strings.HasPrefix(name, "GOOGLE_") {
			value := os.Getenv(name)
			os.Unsetenv(name)
			t.Cleanup(func() { os.Setenv(name, value) })
		}
	}
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("USERPROFILE", home)
	t.Setenv("XDG_CONFIG_HOME", filepath.Join(home, ".config"))
}

func TestCLISurfaceGolden(t *testing.T) {
	isolateCLIEnv(t)
	root, err := cli.NewRootCommand()
	if err != nil {
		t.Fatalf("NewRootCommand() failed: %v", err)
	}
	got := formatSurface(cliSurface(root))

	if *updateSurface {
		path := surfaceGoldenPath(t, true)
		if existing, err := os.ReadFile(path); err == nil {
			d := diffSurface(parseSurface(string(existing)), parseSurface(got))
			if shouldRefuseSurfaceUpdate(d, *allowBreaking) {
				t.Fatalf("Refusing to update %s because the CLI surface has BREAKING changes:\n\n%s\nFix the breaking change, or re-run with -update_cli_surface -allow_breaking if intentional.", surfaceGoldenRel, d)
			}
			if string(existing) == got {
				t.Logf("%s is already up to date", path)
				return
			}
		} else if !errors.Is(err, os.ErrNotExist) {
			t.Fatalf("read %s: %v", path, err)
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatalf("write %s: %v", path, err)
		}
		t.Logf("wrote %s", path)
		return
	}

	path := surfaceGoldenPath(t, false)
	wantBytes, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read CLI surface golden: %v\n\n%s", err, surfaceUpdateHelp)
	}
	d := diffSurface(parseSurface(string(wantBytes)), parseSurface(got))
	if d.empty() {
		if string(wantBytes) != got {
			t.Errorf("%s is not in canonical form.\n\n%s", surfaceGoldenRel, surfaceUpdateHelp)
		}
		return
	}
	if outDir := os.Getenv("TEST_UNDECLARED_OUTPUTS_DIR"); outDir != "" {
		_ = os.WriteFile(filepath.Join(outDir, "cli_surface.golden"), []byte(got), 0o644)
	}
	kind := "additive"
	if d.breaking() {
		kind = "BREAKING"
	}
	t.Errorf("The gemini-api command surface changed (%s); it no longer matches %s.\n\n%s\n%s", kind, surfaceGoldenRel, d, surfaceUpdateHelp)
}

// TestCLISurfaceDetectsDroppedShorthand checks the golden machinery itself
// on a synthetic tree: when a new flag collides with an existing shorthand
// and the generator drops it, the diff must report a breaking change.
func TestCLISurfaceDetectsDroppedShorthand(t *testing.T) {
	build := func(withShorthand bool) *cobra.Command {
		root := &cobra.Command{Use: "gemini-api"}
		root.PersistentFlags().StringP("output-format", "o", "pretty", "")
		envs := &cobra.Command{Use: "environments", Aliases: []string{"env"}}
		create := &cobra.Command{Use: "create", Run: func(*cobra.Command, []string) {}}
		if withShorthand {
			create.Flags().StringP("sources", "s", "", "")
			create.Flags().String("mode", "", "Compute mode. (options: on_demand, self_hosted)")
		} else {
			create.Flags().String("sources", "", "")
			create.Flags().String("system-instruction", "", "")
			create.Flags().String("mode", "", "Compute mode. (options: on_demand)")
		}
		envs.AddCommand(create)
		root.AddCommand(envs)
		return root
	}
	before := parseSurface(formatSurface(cliSurface(build(true))))
	after := parseSurface(formatSurface(cliSurface(build(false))))

	if got, want := before["flag gemini-api environments create --sources"], `short=-s type=string default=""`; got != want {
		t.Fatalf("--sources entry = %q, want %q", got, want)
	}
	if got, want := before["flag gemini-api --output-format"], `short=-o type=string default="pretty" persistent`; got != want {
		t.Errorf("--output-format entry = %q, want %q", got, want)
	}
	if got := before["cmd gemini-api environments"]; got != "aliases=env" {
		t.Errorf("environments entry = %q, want aliases=env", got)
	}
	if _, ok := before["flag gemini-api environments create --output-format"]; ok {
		t.Error("inherited persistent flag recorded on a subcommand; want it only on the declaring command")
	}

	if got, want := before["flag gemini-api environments create --mode"], `short=- type=string default="" options=on_demand,self_hosted`; got != want {
		t.Errorf("--mode entry = %q, want %q", got, want)
	}

	d := diffSurface(before, after)
	if !d.breaking() {
		t.Fatalf("dropping -s from --sources was not reported as breaking:\n%s", d)
	}
	if !shouldRefuseSurfaceUpdate(d, false) {
		t.Error("shouldRefuseSurfaceUpdate(breaking, false) = false, want true")
	}
	if shouldRefuseSurfaceUpdate(d, true) {
		t.Error("shouldRefuseSurfaceUpdate(breaking, true) = true, want false")
	}
	if len(d.changed) != 2 || !strings.Contains(d.changed[0], "--mode") || !strings.Contains(d.changed[1], "--sources") || !strings.Contains(d.changed[1], "short=-s") {
		t.Errorf("changed = %q, want the narrowed --mode options and the lost --sources -s shorthand", d.changed)
	}
	if len(d.added) != 1 || !strings.Contains(d.added[0], "--system-instruction") {
		t.Errorf("added = %q, want the new --system-instruction flag", d.added)
	}

	removed := diffSurface(before, parseSurface(formatSurface(cliSurface(&cobra.Command{Use: "gemini-api"}))))
	if len(removed.removed) == 0 || !removed.breaking() {
		t.Errorf("removing commands was not reported as breaking:\n%s", removed)
	}
	additiveOnly := surfaceDiff{added: []string{"flag gemini-api environments create --label  short=-l type=string default=\"\""}}
	if shouldRefuseSurfaceUpdate(additiveOnly, false) {
		t.Error("shouldRefuseSurfaceUpdate(additive, false) = true, want false")
	}
	if identical := diffSurface(after, after); !identical.empty() {
		t.Errorf("identical surfaces produced a diff:\n%s", identical)
	}
}
